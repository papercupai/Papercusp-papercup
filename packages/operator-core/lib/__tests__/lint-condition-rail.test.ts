import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { baselineCeiling, inventory, lintProblems } from '../../../../scripts/lib/condition-rail-inventory.mjs';

const file = 'packages/example/lib/health/check.ts';
const measure = (source: string, dispositions = {}) => inventory({
  root: '', files: [file], dispositions, readFile: () => source,
});
const manifest = { rows: [], amendments: [] };
const empty = { rowIds: [], amendments: [] };
const bypass = 'function check() { notifyAttention(input); }';

describe('condition-rail lint shrink-only guard (P-006 / R-6)', () => {
  it('rejects a new bypass even if it is given a migrate disposition', () => {
    const live = measure(bypass, { [`owner-only-alarm|${file}`]: { disposition: 'migrate', item: 'P-007' } });
    expect(lintProblems(live, empty, empty, manifest).join()).toMatch(/new rail bypass/);
  });

  it.each([
    'notifyAttention(input); broadcastSevereEvent(event);',
    "console.warn('falling back'); observeFallback('cache', observation);",
    'const health = { degraded: true }; broadcastSevereEvent(event);',
  ])('accepts an observed site: %s', (body) => {
    expect(lintProblems(measure(`function check() { ${body} }`), empty, empty, manifest)).toEqual([]);
  });

  it('accepts existing debt, requires removal when migrated, and refuses re-adding it', () => {
    const live = measure(bypass, { [`owner-only-alarm|${file}`]: { disposition: 'migrate', item: 'P-007' } });
    const baseline = { rowIds: live.rows.map((row) => row.id) };
    expect(lintProblems(live, baseline, baseline, manifest)).toEqual([]);
    const migrated = measure('function check() { notifyAttention(input); broadcastSevereEvent(event); }');
    expect(lintProblems(migrated, baseline, baseline, manifest).join()).toMatch(/obsolete baseline/);
    expect(lintProblems(migrated, empty, baseline, manifest)).toEqual([]);
    expect(lintProblems(live, baseline, empty, manifest).join()).toMatch(/baseline grew/);
    const regenerated = { rowIds: [...baseline.rowIds, 'a newly regenerated bypass'] };
    expect(lintProblems(live, regenerated, baseline, manifest).join()).toMatch(/baseline grew/);
  });

  it('requires a matching amendment-log reason for a new not-applicable site', () => {
    const reason = 'A deliberate authorization audit notice, with no runtime failure predicate';
    const live = measure(bypass, { [`owner-only-alarm|${file}`]: { disposition: 'not-applicable', reason } });
    expect(lintProblems(live, empty, empty, manifest).join()).toMatch(/lacks matching amendment-log reason/);
    const amendment = { rowId: live.rows[0]!.id, author: 'reviewed-inventory', reason,
      change: { disposition: 'not-applicable', reason } };
    expect(lintProblems(live, { ...empty, amendments: [amendment] }, empty, manifest)).toEqual([]);
    expect(lintProblems(live, { ...empty, amendments: [{ ...amendment, reason: '' }] }, empty, manifest).join()).toMatch(/invalid lint amendment/);
    expect(lintProblems(live, { ...empty, amendments: [{ ...amendment, change: { ...amendment.change, reason: 'different reason' } }] }, empty, manifest).join()).toMatch(/lacks matching/);
  });

  it('cannot bless a re-added ID by committing it or by making later metadata-only commits', () => {
    const initial = { rowIds: ['legacy', 'removed'] };
    const removed = { rowIds: ['legacy'] };
    const regrown = { rowIds: ['legacy', 'removed', 'new'] };
    const ceiling = baselineCeiling(initial, [regrown, regrown, removed, initial]);
    expect(ceiling.rowIds).toEqual(['legacy']);
    expect(lintProblems(measure(''), regrown, ceiling, manifest).join()).toMatch(/removed: baseline grew/);
    expect(lintProblems(measure(''), regrown, ceiling, manifest).join()).toMatch(/new: baseline grew/);
  });

  it('fails unreadable sources and stale dispositions', () => {
    const live = measure('');
    expect(lintProblems({ ...live, unreadable: 1 }, empty, empty, manifest).join()).toMatch(/unreadable/);
    expect(lintProblems({ ...live, staleDispositions: ['retired'] }, empty, empty, manifest).join()).toMatch(/stale disposition/);
  });

  it('executes the lint from the gate lint-leg configuration and affected source route', () => {
    const read = (path: string) => readFileSync(new URL(`../../../../${path}`, import.meta.url), 'utf8');
    const rootScripts = JSON.parse(read('package.json')).scripts;
    const coreScripts = JSON.parse(read('packages/operator-core/package.json')).scripts;
    expect(rootScripts['lint:condition-rail']).toMatch(/condition-rail-inventory\.mjs --lint/);
    expect(coreScripts['lint:condition-rail']).toMatch(/condition-rail-inventory\.mjs --lint/);
    const gate = read('apps/operator/lib/release/green-checkpoint.ts');
    expect(gate).toMatch(/script: "lint:condition-rail",\s*outcomeKey: "lintConditionRail"/);
    expect(gate).toContain('"lint:condition-rail": ["lint:condition-rail"]');
    expect(read('scripts/affected-tests.mjs')).toMatch(/script: "lint:condition-rail",[\s\S]{0,500}appliesTo:/);
  });
});

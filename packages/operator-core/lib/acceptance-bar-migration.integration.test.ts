async function insertPlan(slug: string, content: string, status: string) {
  await db.sql`
    INSERT INTO harness_shared.harness_plans
      (workspace_id, harness_slug, plan_slug, title, status, content, content_hash, version)
    VALUES (${WORKSPACE}, ${HARNESS}, ${slug}, ${slug}, ${status}, ${content}, md5(${content}), 1)`;
  await db.sql`
    INSERT INTO harness_shared.plan_items
      (workspace_id, harness_slug, plan_slug, item_id, seq, status, item_text)
    VALUES (${WORKSPACE}, ${HARNESS}, ${slug}, 'P-001', 1, 'todo', 'implement the canonical BAR')`;
  await db.sql`
    INSERT INTO harness_shared.plan_revisions
      (workspace_id, harness_slug, plan_slug, seq, content_hash, content_snapshot)
    VALUES (${WORKSPACE}, ${HARNESS}, ${slug}, 1, md5(${content}), ${content})`;
}

describe('runAcceptanceBarMigrationInDatabase', () => {
  it('adopts a complete explicit legacy-criterion map through the canonical transaction', async () => {
    await insertPlan('legacy-identity', validContent('legacy-identity', 'active'), 'active');
    const legacy = { kind: 'acceptance', subjectPlan: 'legacy-identity', characteristic: 'plan-acceptance',
      ratingScale: ['healthy', 'degraded', 'broken', 'unknown'], criteria: [{
        key: 'canonical-outcome', title: 'Canonical outcome', model: 'The migration writes one canonical BAR and retains its immutable history.',
        method: 'Run the real database migration and replay.', driftMarkers: 'A canonical revision is absent or overwritten.',
      }] };
    await db.sql`INSERT INTO harness_shared.harness_plans
      (workspace_id,harness_slug,plan_slug,title,status,content,content_hash,version,template,template_data)
      VALUES (${WORKSPACE},${HARNESS},'acceptance-legacy-identity','Legacy acceptance','active','legacy body',md5('legacy body'),3,'rubric',${JSON.stringify(legacy)}::text::jsonb)`;
    const before = await runAcceptanceBarMigrationInDatabase({ workspaceId: WORKSPACE, harnessSlug: HARNESS,
      actorId: 'su-migration-test', planSlug: 'legacy-identity', dryRun: true });
    expect(before.outcomes[0]!.status).toBe('refused');
    const preview = await runAcceptanceBarMigrationInDatabase({ workspaceId: WORKSPACE, harnessSlug: HARNESS,
      actorId: 'su-migration-test', planSlug: 'legacy-identity', dryRun: true,
      legacyCriterionMap: { 'R-1': 'canonical-outcome' } });
    expect(preview.outcomes[0]!.status).toBe('dry-run');
    expect(JSON.parse(preview.outcomes[0]!.detail)).toMatchObject({ priorRubricRevision: 3, nextRubricRevision: 4,
      provenance: 'legacy-backfilled', invalidatesPriorProof: true });
    const [unchanged] = await db.sql`SELECT version,template_data FROM harness_shared.harness_plans
      WHERE plan_slug='acceptance-legacy-identity'`;
    expect(Number(unchanged.version)).toBe(3);
    expect(unchanged.template_data).toEqual(legacy);
    const result = await runAcceptanceBarMigrationInDatabase({ workspaceId: WORKSPACE, harnessSlug: HARNESS,
      actorId: 'su-migration-test', planSlug: 'legacy-identity', legacyCriterionMap: { 'R-1': 'canonical-outcome' } });
    expect(result.outcomes[0], result.outcomes[0]!.detail).toMatchObject({ status: 'applied' });
    const [rubric] = await db.sql`SELECT version,template_data FROM harness_shared.harness_plans
      WHERE plan_slug='acceptance-legacy-identity'`;
    expect(Number(rubric.version)).toBe(4);
    expect(rubric.template_data.criteria[0]).toMatchObject({ ...legacy.criteria[0], barKey: 'R-1', mandatory: true,
      barProvenance: { lifecycle: 'legacy-backfilled' } });
  });

  it('types a nullable legacy criterion key before probing live spec mappings', async () => {
    const slug = 'nullable-legacy-bar-key';
    const content = validContent(slug, 'active')
      .replace(
        '**R-1 — Canonical outcome.** The migration writes one canonical BAR.',
        'Legacy requirements predate canonical BAR identifiers.',
      )
      .replace(
        '### Bar-to-work map for this plan\n\n| bar | implementing plan items | evidence plane |\n' +
          '|---|---|---|\n| R-1 | P-001 | tree |\n\n',
        '',
      );
    await insertPlan(slug, content, 'active');

    const legacy = {
      kind: 'acceptance',
      subjectPlan: slug,
      characteristic: 'plan-acceptance',
      ratingScale: ['healthy', 'degraded', 'broken', 'unknown'],
      criteria: [{
        key: 'legacy-outcome',
        title: 'Legacy outcome',
        model: 'The live plan item realizes the legacy outcome.',
        method: 'Inspect the current live spec mapping.',
        driftMarkers: 'The mapped plan item or its live spec is absent.',
        role: 'outcome',
        mandatory: true,
        barHash: 'a'.repeat(64),
        evidencePlane: 'tree',
        passRatings: ['healthy'],
      }],
    };
    await db.sql`INSERT INTO harness_shared.harness_plans
      (workspace_id,harness_slug,plan_slug,title,status,content,content_hash,version,template,template_data)
      VALUES (${WORKSPACE},${HARNESS},${`acceptance-${slug}`},'Legacy acceptance','active','legacy body',
              md5('legacy body'),2,'rubric',${JSON.stringify(legacy)}::text::jsonb)`;
    await db.sql`INSERT INTO harness_shared.plan_spec_clauses
      (workspace_id,harness_slug,plan_slug,spec_id,current_revision,created_by)
      VALUES (${WORKSPACE},${HARNESS},${slug},'SPEC-001',1,'su-migration-test')`;
    await db.sql`INSERT INTO harness_shared.plan_spec_clause_revisions
      (workspace_id,harness_slug,plan_slug,spec_id,revision,plan_item_id,behavior,behavior_class,
       required_evidence,required_test_layers,mutation_required,lifecycle_status,content_hash,
       created_by,accepted_by,accepted_at)
      VALUES (${WORKSPACE},${HARNESS},${slug},'SPEC-001',1,'P-001','The legacy outcome remains realized.',
              'happy-path',ARRAY['real database trace']::text[],ARRAY['integration']::text[],false,
              'active',${'b'.repeat(64)},'su-migration-test','su-migration-test',now())`;

    const [before] = await db.sql`SELECT content,version,acceptance_bar_epoch,acceptance_bar_cohort,
      acceptance_bar_set_hash FROM harness_shared.harness_plans WHERE plan_slug=${slug}`;
    const result = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      planSlug: slug,
      dryRun: true,
    });
    expect(result.outcomes[0]).toMatchObject({
      planSlug: slug,
      status: 'refused',
      decision: { action: 'legacy-backfill', cohort: 'post-epoch' },
    });
    expect(result.outcomes[0]!.detail).toMatch(/bar_rubric_conflict/);
    expect(result.outcomes[0]!.detail).not.toMatch(/could not determine data type of parameter/i);
    const [after] = await db.sql`SELECT content,version,acceptance_bar_epoch,acceptance_bar_cohort,
      acceptance_bar_set_hash FROM harness_shared.harness_plans WHERE plan_slug=${slug}`;
    expect(after).toEqual(before);
  });

  // EI-23379913422335853. The sibling test above passes only because its criterion omits
  // `barKey`; every rubric authored by the current template SETS one, so the strict
  // `r.source_bar_key = barKey` match was live in the common case and excluded every clause of
  // a plan whose clauses predate bar-key attribution — the exact cohort legacy-backfill exists
  // for. These two pin the fallback AND the attribution guard that bounds it.
  const legacyRubricWithBarKey = (slug: string, barKey: string) => ({
    kind: 'acceptance',
    subjectPlan: slug,
    characteristic: 'plan-acceptance',
    ratingScale: ['healthy', 'degraded', 'broken', 'unknown'],
    criteria: [{
      key: 'legacy-outcome',
      title: 'Legacy outcome',
      model: 'The live plan item realizes the legacy outcome.',
      method: 'Inspect the current live spec mapping.',
      driftMarkers: 'The mapped plan item or its live spec is absent.',
      role: 'outcome',
      mandatory: true,
      barKey,
      barHash: 'a'.repeat(64),
      evidencePlane: 'tree',
      passRatings: ['healthy'],
    }],
  });

  const legacyContentWithoutBars = (slug: string) => validContent(slug, 'active')
    .replace(
      '**R-1 — Canonical outcome.** The migration writes one canonical BAR.',
      'Legacy requirements predate canonical BAR identifiers.',
    )
    .replace(
      '### Bar-to-work map for this plan\n\n| bar | implementing plan items | evidence plane |\n' +
        '|---|---|---|\n| R-1 | P-001 | tree |\n\n',
      '',
    );

  const insertLegacyClause = async (
    slug: string,
    specId: string,
    planItemId: string,
    sourceBarKey: string | null,
  ) => {
    await db.sql`INSERT INTO harness_shared.plan_spec_clauses
      (workspace_id,harness_slug,plan_slug,spec_id,current_revision,created_by)
      VALUES (${WORKSPACE},${HARNESS},${slug},${specId},1,'su-migration-test')`;
    await db.sql`INSERT INTO harness_shared.plan_spec_clause_revisions
      (workspace_id,harness_slug,plan_slug,spec_id,revision,plan_item_id,source_bar_key,behavior,behavior_class,
       required_evidence,required_test_layers,mutation_required,lifecycle_status,content_hash,
       created_by,accepted_by,accepted_at)
      VALUES (${WORKSPACE},${HARNESS},${slug},${specId},1,${planItemId},${sourceBarKey},
              'The legacy outcome remains realized.',
              'happy-path',ARRAY['real database trace']::text[],ARRAY['integration']::text[],false,
              'active',${'b'.repeat(64)},'su-migration-test','su-migration-test',now())`;
  };

  it('legacy-backfills a barKey criterion when no clause in the plan carries bar attribution', async () => {
    const slug = 'legacy-bar-key-unattributed';
    await insertPlan(slug, legacyContentWithoutBars(slug), 'active');
    await db.sql`INSERT INTO harness_shared.harness_plans
      (workspace_id,harness_slug,plan_slug,title,status,content,content_hash,version,template,template_data)
      VALUES (${WORKSPACE},${HARNESS},${`acceptance-${slug}`},'Legacy acceptance','active','legacy body',
              md5('legacy body'),2,'rubric',${JSON.stringify(legacyRubricWithBarKey(slug, 'R-1'))}::text::jsonb)`;
    // source_bar_key NULL — the legacy shape: clauses generated before bar-key attribution existed.
    await insertLegacyClause(slug, 'SPEC-001', 'P-001', null);

    const result = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      planSlug: slug,
      dryRun: true,
    });

    // The claim under test is the CLASSIFICATION. Before the fix this was
    // 'bar-backfill-required' ("fabricated BARs are forbidden") and the cohort was unreachable.
    expect(result.outcomes[0]!.decision.action).toBe('legacy-backfill');
    expect(result.outcomes[0]!.decision.action).not.toBe('bar-backfill-required');
  });

  it('still refuses when the plan DOES attribute clauses to a different bar', async () => {
    const slug = 'legacy-bar-key-attributed-elsewhere';
    await insertPlan(slug, legacyContentWithoutBars(slug), 'active');
    await db.sql`INSERT INTO harness_shared.harness_plans
      (workspace_id,harness_slug,plan_slug,title,status,content,content_hash,version,template,template_data)
      VALUES (${WORKSPACE},${HARNESS},${`acceptance-${slug}`},'Legacy acceptance','active','legacy body',
              md5('legacy body'),2,'rubric',${JSON.stringify(legacyRubricWithBarKey(slug, 'R-1'))}::text::jsonb)`;
    // This plan DOES use bar keys, just not R-1 — so the strict match must stay in force and the
    // fallback must NOT fire, or the migration would mis-attribute R-9's clause to R-1.
    await insertLegacyClause(slug, 'SPEC-001', 'P-001', 'R-9');

    const result = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      planSlug: slug,
      dryRun: true,
    });

    expect(result.outcomes[0]!.decision.action).toBe('bar-backfill-required');
  });

  it('keeps a post-epoch executable plan in its cohort while recording honestly backfilled BARs', async () => {
    await insertPlan('strict-late-bars', validContent('strict-late-bars', 'active'), 'active');
    await db.sql`UPDATE harness_shared.harness_plans
      SET acceptance_bar_epoch=1, acceptance_bar_cohort='post-epoch' WHERE plan_slug='strict-late-bars'`;
    const result = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE, harnessSlug: HARNESS, actorId: 'su-migration-test',
      planSlug: 'strict-late-bars', now: new Date('2026-09-05T15:00:00Z'),
    });
    expect(result.outcomes[0]).toMatchObject({ status: 'applied', decision: { cohort: 'post-epoch' } });
    const [plan] = await db.sql`SELECT acceptance_bar_cohort, acceptance_bar_set_hash
      FROM harness_shared.harness_plans WHERE plan_slug='strict-late-bars'`;
    expect(plan.acceptance_bar_cohort).toBe('post-epoch');
    expect(plan.acceptance_bar_set_hash).toMatch(/^[a-f0-9]{64}$/);
    const [rubric] = await db.sql`SELECT template_data FROM harness_shared.harness_plans
      WHERE plan_slug='acceptance-strict-late-bars'`;
    expect(rubric.template_data.barContract.cohort).toBe('post-epoch');
    expect(rubric.template_data.criteria[0].barProvenance).toMatchObject({
      lifecycle: 'legacy-backfilled', declaredBy: 'su-migration-test', declaredAt: '2026-09-05T15:00:00.000Z',
    });
    const replay = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE, harnessSlug: HARNESS, actorId: 'su-migration-test', planSlug: 'strict-late-bars',
    });
    expect(replay.outcomes).toEqual([]);
  });

  it('dry-runs, applies through the canonical writer, and converges on rerun', async () => {
    const content = validContent('migration-target');
    await insertPlan('migration-target', content, 'draft');

    const dry = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 1,
      dryRun: true,
    });
    expect(dry.outcomes).toHaveLength(1);
    expect(dry.outcomes[0]).toMatchObject({ status: 'dry-run', planSlug: 'migration-target' });
    await expect(db.sql`
      SELECT acceptance_bar_set_hash FROM harness_shared.harness_plans
       WHERE plan_slug = 'migration-target'
    `).resolves.toEqual([{ acceptance_bar_set_hash: null }]);

    const applied = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 1,
    });
    expect(applied.outcomes[0]).toMatchObject({ status: 'applied' });
    await expect(db.sql`
      SELECT acceptance_bar_epoch, acceptance_bar_cohort, acceptance_bar_set_hash,
             acceptance_bar_rubric_slug
        FROM harness_shared.harness_plans WHERE plan_slug = 'migration-target'
    `).resolves.toEqual([expect.objectContaining({
      acceptance_bar_epoch: 1,
      acceptance_bar_cohort: 'post-epoch',
      acceptance_bar_set_hash: expect.stringMatching(/^[a-f0-9]{64}$/),
      acceptance_bar_rubric_slug: 'acceptance-migration-target',
    })]);

    const rerun = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 1,
    });
    expect(rerun).toMatchObject({ complete: true, outcomes: [] });
    await expect(db.sql`
      SELECT count(*)::int AS n FROM harness_shared.harness_plans
       WHERE plan_slug = 'acceptance-migration-target'
    `).resolves.toEqual([{ n: 1 }]);
  });

  it('persists a slug cursor across partial pages without replaying the first plan', async () => {
    await insertPlan('cursor-a', validContent('cursor-a'), 'draft');
    await insertPlan('cursor-b', validContent('cursor-b'), 'draft');

    const first = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 1,
    });
    expect(first).toMatchObject({ complete: false, nextCursor: 'cursor-a' });
    expect(first.outcomes).toMatchObject([{ planSlug: 'cursor-a', status: 'applied' }]);

    const second = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 1,
      cursor: first.nextCursor,
    });
    expect(second).toMatchObject({ complete: true, nextCursor: null });
    expect(second.outcomes).toMatchObject([{ planSlug: 'cursor-b', status: 'applied' }]);
    await expect(db.sql`
      SELECT plan_slug, acceptance_bar_set_hash
        FROM harness_shared.harness_plans
       WHERE plan_slug LIKE 'cursor-%'
       ORDER BY plan_slug
    `).resolves.toEqual([
      expect.objectContaining({ plan_slug: 'cursor-a', acceptance_bar_set_hash: expect.stringMatching(/^[a-f0-9]{64}$/) }),
      expect.objectContaining({ plan_slug: 'cursor-b', acceptance_bar_set_hash: expect.stringMatching(/^[a-f0-9]{64}$/) }),
    ]);
  });

  it('rolls back one failed plan while committing a sibling and advancing the cursor', async () => {
    await insertPlan('a-valid', validContent('a-valid', 'ready'), 'ready');
    const invalid = validContent('b-invalid', 'ready').replace('| R-1 | P-001 | tree |', '');
    await insertPlan('b-invalid', invalid, 'ready');

    const result = await runAcceptanceBarMigrationInDatabase({
      workspaceId: WORKSPACE,
      harnessSlug: HARNESS,
      actorId: 'su-migration-test',
      batchSize: 2,
    });
    expect(result).toMatchObject({ complete: true, outcomes: [
      { planSlug: 'a-valid', status: 'applied' },
      { planSlug: 'b-invalid', status: 'failed' },
    ] });
    await expect(db.sql`
      SELECT plan_slug, acceptance_bar_set_hash, acceptance_bar_cohort
        FROM harness_shared.harness_plans
       WHERE plan_slug IN ('a-valid', 'b-invalid')
       ORDER BY plan_slug
    `).resolves.toEqual([
      expect.objectContaining({ plan_slug: 'a-valid', acceptance_bar_set_hash: expect.stringMatching(/^[a-f0-9]{64}$/) }),
      expect.objectContaining({ plan_slug: 'b-invalid', acceptance_bar_set_hash: null, acceptance_bar_cohort: 'post-epoch' }),
    ]);
  });
});

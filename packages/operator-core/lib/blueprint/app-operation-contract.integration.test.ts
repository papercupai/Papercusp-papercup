/**
 * R-1 / P-001 (plan app-agent-tasks-durable-execution-2026-10-06, D-001) — the
 * contract the connected apps (Email, Calendar, Phone) call is pinned here.
 *
 * Apps reach agent work through ONE surface: the seven public `blueprint:*`
 * operation tools, called with the typed `BlueprintOperationClient` over the
 * projected port (the same port pot-app-seam's host adapters wrap). This suite:
 *   • pins the wire shapes D-001 records, so a contract change fails HERE before
 *     an app or the seam silently drifts from it;
 *   • drives an app-shaped declared operation (an email draft-reply: work-item
 *     target, agent execution, declared input/result schemas) through REAL
 *     projected dispatch on HTTP and MCP against a fresh PostgreSQL, and proves
 *     the returned handle reads a TERMINAL result: `ready` with output that
 *     satisfies the declared resultSchema, or a non-ready terminal state that
 *     carries a reason and no output.
 *
 * Settlement (the executor writing its validated `blueprintResult`) is simulated
 * with the same durable write the P-017 suite uses; executor behaviour is covered
 * by the parent plan's P-008/P-009 suites.
 */

async function settle(handle: BlueprintOperationHandle, write: { status: string; output?: unknown }): Promise<void> {
  if (handle.target.kind !== 'work-item') throw new Error('expected a direct work-item target');
  const payload = write.output === undefined ? {} : { blueprintResult: {
    operationId: handle.operationId, specificationRevision: handle.specificationRevision,
    output: write.output, evidenceRef: 'verification:app-operation-contract',
  } };
  await db.sql`
    UPDATE harness_shared.work_items
       SET status = ${write.status}, authority = 'committed',
           payload = payload || ${JSON.stringify(payload)}::text::jsonb
     WHERE feature_id = ${handle.target.id} AND workspace_id = ${WORKSPACE} AND harness_slug = ${APP_HARNESS}`;
}

/** Minimal check of an output against the declared resultSchema (required + types + no extras). */
function satisfiesDeclaredResult(output: unknown): boolean {
  if (!output || typeof output !== 'object' || Array.isArray(output)) return false;
  const record = output as Record<string, unknown>;
  const props = DRAFT_RESULT_SCHEMA.properties as Record<string, { type: string }>;
  return DRAFT_RESULT_SCHEMA.required.every((k) => typeof record[k] === props[k].type) &&
    Object.keys(record).every((k) => k in props);
}

describe('R-1 pinned app operation contract (D-001)', () => {
  it('names exactly the seven public blueprint:* lifecycle tools the apps call', () => {
    expect(BLUEPRINT_OPERATION_TOOLS).toEqual({
      submit: 'blueprint:submit', status: 'blueprint:status', result: 'blueprint:result',
      events: 'blueprint:events', cancel: 'blueprint:cancel', signal: 'blueprint:signal', resume: 'blueprint:resume',
    });
    for (const name of Object.values(BLUEPRINT_OPERATION_TOOLS)) {
      expect(lookupByMcpName(name)?.expose.http?.path, name).toBeTruthy();
    }
  });

  it('keeps the request, handle, status, events and cancel shapes D-001 records', () => {
    // privateInput is the D-014 extension (operation-scoped transient handoff); it stays optional,
    // so a D-001 request without it is still valid.
    expect(Object.keys(SubmitArgsSchema.shape).sort()).toEqual(
      ['harness', 'input', 'operationId', 'privateInput', 'requestKey', 'summary', 'title']);
    expect(SubmitArgsSchema.shape.privateInput.isOptional()).toBe(true);
    expect(Object.keys(EventsArgsSchema.shape).sort()).toEqual(['cursor', 'handle', 'limit']);
    expect(Object.keys(CancelArgsSchema.shape).sort()).toEqual(['handle', 'reason', 'requestKey']);
    expect(Object.keys(BlueprintOperationStatusSchema.shape).sort()).toEqual(
      ['cancellationRequested', 'handle', 'items', 'outcome', 'phase', 'planRun', 'wait']);
    expect(BlueprintOperationStatusSchema.shape.phase.options).toEqual(['accepted', 'dispatched', 'waiting', 'terminal']);
    const handle = { workspaceId: WORKSPACE, harnessSlug: APP_HARNESS, receiptId: 1, operationId: 'draft-reply',
      specificationRevision: 'a'.repeat(64), target: { kind: 'work-item', id: 'WI-1' } };
    expect(BlueprintOperationHandleSchema.parse(handle)).toEqual(handle);
    // Only `ready` may carry output; every other terminal state carries a reason instead.
    const status = { handle, phase: 'terminal', outcome: 'dropped', items: [], planRun: null,
      cancellationRequested: false, wait: null };
    expect(BlueprintOperationResultSchema.safeParse({ state: 'dropped', status, reason: 'x' }).success).toBe(true);
    expect(BlueprintOperationResultSchema.safeParse({ state: 'dropped', status }).success).toBe(false);
    // `ready` needs BOTH output and its evidence ref — each requirement asserted in isolation,
    // beside a positive control, so relaxing either one fails here on its own.
    const ready = { state: 'ready', status, output: { draftId: 'd', body: 'b' }, evidenceRef: 'verification:x' };
    expect(BlueprintOperationResultSchema.safeParse(ready).success).toBe(true);
    expect(BlueprintOperationResultSchema.safeParse({ ...ready, evidenceRef: undefined }).success).toBe(false);
    expect(BlueprintOperationResultSchema.safeParse({ state: 'ready', status, evidenceRef: 'verification:x' }).success)
      .toBe(false);
    expect(BlueprintOperationCancelReceiptSchema.safeParse({ eventId: 'e', replayed: false, accepted: true,
      wakeQueued: false, handled: false }).success).toBe(false);
  });
});

describe.each<Transport>(['http', 'mcp'])('R-1 app operation through the public contract over %s', (transport) => {
  it('reaches a ready terminal result its returned handle reads, with output satisfying the declared resultSchema', async () => {
    const client = appClient(transport);
    const handle = await client.submit({
      operationId: 'draft-reply', requestKey: draftKey('thr-1'),
      input: { mailboxId: 'mbx-1', threadId: 'thr-1' }, title: 'Draft reply to thr-1',
    });
    expect(BlueprintOperationHandleSchema.parse(handle)).toMatchObject({
      workspaceId: WORKSPACE, harnessSlug: APP_HARNESS, operationId: 'draft-reply', target: { kind: 'work-item' },
    });
    // The domain key replays one durable operation; reusing it with other input is refused.
    expect(await client.submit({ operationId: 'draft-reply', requestKey: draftKey('thr-1'),
      input: { mailboxId: 'mbx-1', threadId: 'thr-1' }, title: 'Draft reply to thr-1' })).toEqual(handle);
    await expect(client.submit({ operationId: 'draft-reply', requestKey: draftKey('thr-1'),
      input: { mailboxId: 'mbx-1', threadId: 'thr-2' } })).rejects.toThrow(/input_conflict/);
    // Input outside the declared inputSchema never creates work.
    await expect(client.submit({ operationId: 'draft-reply', requestKey: draftKey('thr-bad'),
      input: { mailboxId: 'mbx-1' } as never })).rejects.toThrow();

    expect(await client.status(handle)).toMatchObject({ phase: 'accepted', outcome: null });
    expect(await client.result(handle)).toMatchObject({ state: 'pending' });
    const firstPage = BlueprintOperationEventsPageSchema.parse(await client.events(handle));
    expect(firstPage.events.length).toBeGreaterThan(0);

    await settle(handle, { status: 'passed', output: { draftId: 'draft-1', body: 'Thanks — confirming Tuesday.' } });
    const terminal = await client.status(handle);
    expect(terminal).toMatchObject({ phase: 'terminal', outcome: 'succeeded' });
    const result = BlueprintOperationResultSchema.parse(await client.result(handle));
    expect(result).toMatchObject({ state: 'ready', evidenceRef: 'verification:app-operation-contract' });
    if (result.state !== 'ready') throw new Error('expected ready');
    expect(satisfiesDeclaredResult(result.output)).toBe(true);
    expect(result.status.handle).toEqual(handle);
  });

  it('reaches a non-ready terminal result that carries a reason and no output when the work is dropped', async () => {
    const client = appClient(transport);
    const handle = await client.submit({
      operationId: 'draft-reply', requestKey: draftKey('thr-dropped'),
      input: { mailboxId: 'mbx-1', threadId: 'thr-dropped' },
    });
    await settle(handle, { status: 'dropped' });
    expect(await client.status(handle)).toMatchObject({ phase: 'terminal', outcome: 'dropped' });
    const result = BlueprintOperationResultSchema.parse(await client.result(handle));
    expect(result.state).toBe('dropped');
    expect(result).not.toHaveProperty('output');
    expect(result).toHaveProperty('reason');
  });

  it('accepts a cancel through the handle and reflects it on status before the work settles', async () => {
    const client = appClient(transport);
    const handle = await client.submit({
      operationId: 'draft-reply', requestKey: draftKey('thr-cancel'),
      input: { mailboxId: 'mbx-1', threadId: 'thr-cancel' },
    });
    const receipt = BlueprintOperationCancelReceiptSchema.parse(
      await client.cancel(handle, { requestKey: 'cancel:thr-cancel', reason: 'thread archived' }));
    expect(receipt).toMatchObject({ accepted: true, handled: false });
    expect(await client.status(handle)).toMatchObject({ cancellationRequested: true });
    // A replayed cancel is the same durable control input.
    expect(await client.cancel(handle, { requestKey: 'cancel:thr-cancel', reason: 'thread archived' }))
      .toMatchObject({ eventId: receipt.eventId, replayed: true });
  });
});

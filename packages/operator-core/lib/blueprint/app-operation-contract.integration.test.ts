type Transport = 'http' | 'mcp';

const HTTP_EXTRAS: HttpToolHostExtras = {
  validateSuperuser: () => false,
  resolvePrincipalAndTx: async (bearer) => bearer === 'token-email-app'
    ? { principal: { ...APP_PRINCIPAL, capabilities: new Set(APP_PRINCIPAL.capabilities) }, tx: h.sql }
    : null,
  deps: {},
};

/** A refusal must throw — the contract `ProjectedToolInvoke` requires it. */
async function invokeVia(transport: Transport, name: string, args: Record<string, unknown>): Promise<unknown> {
  if (transport === 'http') {
    const projected = lookupByMcpName(name);
    if (!projected?.expose.http) throw new Error(`${name} is not HTTP-projected`);
    const res = await handleHttpToolRequest({
      method: 'POST', pathname: projected.expose.http.path, searchParams: new URLSearchParams(),
      headers: { authorization: 'Bearer token-email-app' }, body: args,
    }, HTTP_EXTRAS);
    const body = res.body as { error?: { code: string; message: string } } & ToolResult;
    if (res.status !== 200) throw new Error(`${body.error!.code}: ${body.error!.message}`);
    return unwrapToolResult(body);
  }
  const ctx = {
    workspaceId: WORKSPACE, harnessSlug: '*', role: 'papercup', featureId: null, chunkId: null,
    runId: globalThis.crypto.randomUUID(), spawnId: APP_PRINCIPAL.slug, parentSpawnId: null, uiClientId: null,
    principal: { kind: 'pi', ...APP_PRINCIPAL, capabilities: new Set(APP_PRINCIPAL.capabilities) },
    tx: h.sql, isSuperuser: false, transport: 'mcp',
    log: () => {}, progress: () => {}, emit: () => {}, signal: new AbortController().signal,
  } as unknown as UnifiedToolContext;
  const out = await dispatchProjectedToolToMcp(lookupByMcpName(name)!, name, args, ctx, {});
  if (out.isError) throw new Error((out.content?.[0] as { text?: string } | undefined)?.text ?? 'refused');
  return unwrapToolResult(out as ToolResult);
}


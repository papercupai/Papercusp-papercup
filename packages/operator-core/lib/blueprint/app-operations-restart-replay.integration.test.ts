/**
 * app-operations-restart-replay.integration.test.ts — R-10 of plan
 * app-agent-tasks-durable-execution-2026-10-06 (P-010 / WI-10006462).
 *
 * The claim under test: an operator restart during an in-flight app operation
 * resumes it to ONE terminal result without a duplicate side effect. The Email,
 * Calendar and Phone apps submit work-item-target blueprint operations through
 * the pot-app seam; when the operator restarts, their sidecars replay the same
 * request key. A work-item-target operation is durable in PostgreSQL only (the
 * `blueprint_operation_invocations` receipt plus the target `work_items` row —
 * DBOS is used only for plan targets), so a restart is survivable exactly when
 * nothing the operation needs lives in process memory.
 *
 * WHAT "RESTART" MEANS HERE (and what it does not). `restartOperationRuntime()`
 * drops everything an operator process holds: it ENDS the runtime's PostgreSQL
 * pool, empties the module registry (`vi.resetModules()`, which also drops the
 * admission flight map and the nested-acquire gates), clears every
 * `pinModuleState` singleton (`resetPinnedModuleStateForTest()` — those live on
 * globalThis and survive a module reset otherwise), then opens a NEW pool and
 * re-imports the service. The restart is itself asserted (fresh module
 * namespaces, a different pool) so a no-op restart cannot pass vacuously. It is
 * an in-process restart over the same database; the live operator restart on the
 * current build is the corroborating acceptance evidence parked on the plan.
 *
 * Every count is taken on a separate OBSERVER connection (`db.sql`), never the
 * runtime pool, so the runtime under test does not grade its own writes.
 *
 * Scope: R-2 (seam replay) and R-9 (booking dial replay) are other idempotency
 * layers with their own tests; this file covers only operator-restart replay.
 */

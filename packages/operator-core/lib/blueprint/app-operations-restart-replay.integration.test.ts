describe('R-10 — an operator restart mid-operation resumes to one terminal result, no duplicate side effect', () => {
  it('uses a compilable pinned worker fixture and rejects removing its identity pin', () => {
    expect(() => compileAgentSpecification({ source: FIXTURE_SOURCE })).not.toThrow();
    const unpinned = {
      ...FIXTURE_SOURCE,
      operations: FIXTURE_SOURCE.operations.map(({ policy: _policy, ...operation }) => operation),
    };
    expect(() => compileAgentSpecification({ source: unpinned })).toThrow('operation-unpinned-agent');
  });

  it('restart while the applied worker holds the item: replay keeps one receipt and one item, completion lands once', async () => {
    const callerId = 'email-app';
    const requestKey = 'thread-4711:draft';
    const request = {
      workspaceId: WORKSPACE, harnessSlug: HARNESS, callerId, operationId: OPERATION,
      requestKey, input: { threadId: 'thread-4711' }, title: 'Draft reply for thread 4711',
    };
    const worker = 'operation-worker-restart';

    // ── Runtime 1: accept, then the applied worker takes it (in flight). ──
    let rt = await startOperationRuntime(1);
    const first = await rt.service.submitBlueprintOperation(rt.sql, request);
    expect(first.target.kind).toBe('work-item');
    expect(await census(callerId, requestKey)).toEqual({ receipts: 1, items: 1 });
    const itemId = await applyWorkerSession(rt, first, worker);
    const claimed = await rt.workItems.claimWorkItem(itemId, worker, { harness: HARNESS });
    expect(claimed?.assignee).toBe(worker);
    expect(await rt.service.getBlueprintOperationStatus(rt.sql, first, callerId))
      .toMatchObject({ phase: 'dispatched', outcome: null });

    // ── Restart mid-operation. ──
    rt = await restartOperationRuntime(rt);

    // Not reset and not stuck: the fresh runtime reads the same in-flight phase.
    expect(await rt.service.getBlueprintOperationStatus(rt.sql, first, callerId))
      .toMatchObject({ phase: 'dispatched', outcome: null });
    // The app sidecar reconnects and replays its request key through its client.
    const appClient = new rt.client.BlueprintOperationClient<{
      'draft-reply': { input: { threadId: string }; output: { draft: string }; signals: Record<string, never> };
    }>(rt.client.createPgBlueprintOperationPort(rt.sql), { workspaceId: WORKSPACE, harnessSlug: HARNESS, callerId });
    const replayed = await appClient.submit({
      operationId: OPERATION, input: { threadId: 'thread-4711' }, requestKey, title: request.title,
    });
    expect(replayed).toEqual(first);
    expect(await census(callerId, requestKey)).toEqual({ receipts: 1, items: 1 });
    // The replay did not release or re-assign the in-flight claim.
    expect((await rt.workItems.getWorkItem(itemId, HARNESS))?.assignee).toBe(worker);

    // ── The applied worker finishes on the restarted runtime. ──
    const done = await rt.workItems.setWorkItemState(itemId, 'done', {
      harness: HARNESS, by: worker, completionAuthority: 'committed',
      outputPayload: { draft: 'Thanks, Thursday works.' },
    });
    expect(done?.state).toBe('done');
    expect(await appClient.result(replayed)).toMatchObject({ state: 'ready', output: { draft: 'Thanks, Thursday works.' } });

    // Late duplicate completions cannot produce a second terminal result.
    await expect(rt.workItems.setWorkItemState(itemId, 'done', {
      harness: HARNESS, by: callerId, completionAuthority: 'committed',
      outputPayload: { draft: 'a different draft' },
    })).rejects.toThrow('accepted operation item requires its applied worker');
    // The SAME applied worker re-closing with a different output must not replace
    // the settled result (whether it is refused or ignored is the code's choice).
    await rt.workItems.setWorkItemState(itemId, 'done', {
      harness: HARNESS, by: worker, completionAuthority: 'committed',
      outputPayload: { draft: 'a different draft' },
    }).catch(() => undefined);
    expect(await appClient.result(replayed)).toMatchObject({ state: 'ready', output: { draft: 'Thanks, Thursday works.' } });
    expect(await storedOutput(itemId)).toEqual({ draft: 'Thanks, Thursday works.' });
    expect(await terminalWorkItemEvents(rt, first, callerId)).toBe(1);

    // ── A second restart after completion: the replay returns the same settled result. ──
    rt = await restartOperationRuntime(rt);
    const lateReplay = await rt.service.submitBlueprintOperation(rt.sql, request);
    expect(lateReplay).toEqual(first);
    expect(await rt.service.getBlueprintOperationResult(rt.sql, lateReplay, callerId))
      .toMatchObject({ state: 'ready', output: { draft: 'Thanks, Thursday works.' } });
    expect(await rt.service.getBlueprintOperationStatus(rt.sql, lateReplay, callerId))
      .toMatchObject({ phase: 'terminal', outcome: 'succeeded' });
    expect(await census(callerId, requestKey)).toEqual({ receipts: 1, items: 1 });
    expect(await terminalWorkItemEvents(rt, first, callerId)).toBe(1);
    await rt.sql.end({ timeout: 5 });
    h.sql = db.sql;
  }, 60_000);

  it('operator death inside admission: the replay adopts the committed item and writes one receipt, never a second item', async () => {
    const callerId = 'calendar-app';
    const requestKey = 'event-88:rev-3:prep';
    const request = {
      workspaceId: WORKSPACE, harnessSlug: HARNESS, callerId, operationId: OPERATION,
      requestKey, input: { threadId: 'event-88' }, title: 'Prepare for event 88',
    };
    const worker = 'operation-worker-crash';

    // The process dies the instant its receipt write reaches PostgreSQL: the
    // trigger terminates the inserting backend, so the receipt transaction never
    // commits. pg_sleep services the pending interrupt inside the trigger, so the
    // death cannot slip past the commit.
    await db.sql.unsafe(`
      CREATE FUNCTION harness_shared.restart_replay_die() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN
        PERFORM pg_terminate_backend(pg_backend_pid());
        PERFORM pg_sleep(5);
        RETURN NEW;
      END $$;
      CREATE TRIGGER restart_replay_die AFTER INSERT ON harness_shared.blueprint_operation_invocations
        FOR EACH ROW EXECUTE FUNCTION harness_shared.restart_replay_die();`).simple();
    let rt = await startOperationRuntime(10);
    try {
      await expect(rt.service.submitBlueprintOperation(rt.sql, request)).rejects.toThrow();
    } finally {
      await db.sql.unsafe(`
        DROP TRIGGER IF EXISTS restart_replay_die ON harness_shared.blueprint_operation_invocations;
        DROP FUNCTION IF EXISTS harness_shared.restart_replay_die();`).simple();
    }
    // The death left the side effect (the item) committed without its receipt.
    expect(await census(callerId, requestKey)).toEqual({ receipts: 0, items: 1 });
    const [orphanId] = await itemIdsFor(callerId, requestKey);

    rt = await restartOperationRuntime(rt);
    const handle = await rt.service.submitBlueprintOperation(rt.sql, request);
    expect(handle.target).toEqual({ kind: 'work-item', id: orphanId });
    expect(await census(callerId, requestKey)).toEqual({ receipts: 1, items: 1 });
    // A second replay on the same runtime stays at one of each.
    expect(await rt.service.submitBlueprintOperation(rt.sql, request)).toEqual(handle);
    expect(await census(callerId, requestKey)).toEqual({ receipts: 1, items: 1 });

    // The recovered operation is not stuck: the applied worker can take it and settle it once.
    await applyWorkerSession(rt, handle, worker);
    expect((await rt.workItems.claimWorkItem(orphanId, worker, { harness: HARNESS }))?.assignee).toBe(worker);
    await rt.workItems.setWorkItemState(orphanId, 'done', {
      harness: HARNESS, by: worker, completionAuthority: 'committed',
      outputPayload: { draft: 'Agenda: budget, hiring.' },
    });
    expect(await rt.service.getBlueprintOperationResult(rt.sql, handle, callerId))
      .toMatchObject({ state: 'ready', output: { draft: 'Agenda: budget, hiring.' } });
    expect(await terminalWorkItemEvents(rt, handle, callerId)).toBe(1);
    await rt.sql.end({ timeout: 5 });
    h.sql = db.sql;
  }, 60_000);
});

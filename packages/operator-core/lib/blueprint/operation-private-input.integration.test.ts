/**
 * D-014 (plan app-agent-tasks-durable-execution-2026-10-06, WI-10006699) —
 * operation private input against a fresh PostgreSQL and the REAL projected
 * blueprint:submit / blueprint:read-private-input tools.
 *
 * Proves:
 *   • submit stores privateInput OUTSIDE the work item (the payload never carries
 *     it), keyed by the invocation, with sha256 over JSON.stringify(value);
 *   • a same-key replay with identical content is a no-op; different content is
 *     refused private_input_conflict; undeclared / missing / invalid private input
 *     is refused;
 *   • only the CURRENT holder of the non-terminal item can read it, and the read
 *     returns the exact content and its sha256;
 *   • a replay after the row was deleted does not re-create it;
 *   • the retention sweep deletes rows of terminal items and expired rows and keeps
 *     an in-flight row.
 */

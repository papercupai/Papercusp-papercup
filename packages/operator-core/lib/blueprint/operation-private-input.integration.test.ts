type Segment = [number, string, string];
const SEGMENTS: Segment[] = [[1, 'agent', 'Hello, this is the assistant.'], [2, 'guest', 'Hi — confirming Tuesday.']];
const sha256 = (value: unknown) => createHash('sha256').update(JSON.stringify(value), 'utf8').digest('hex');

function baseCtx(): Record<string, unknown> {
  return {
    workspaceId: WORKSPACE, harnessSlug: '*', role: 'papercup', featureId: null, chunkId: null,
    runId: globalThis.crypto.randomUUID(), parentSpawnId: null,
    log: () => {}, progress: () => {}, emit: () => {}, signal: new AbortController().signal,
    tx: h.sql, transport: 'mcp',
  };
}

/** The app's call: an authenticated app principal. */
const appCtx = () => ({
  ...baseCtx(), spawnId: APP_PRINCIPAL.slug, uiClientId: null, isSuperuser: false,
  principal: { kind: 'pi', ...APP_PRINCIPAL, capabilities: new Set(APP_PRINCIPAL.capabilities) },
}) as unknown as UnifiedToolContext;

/** A worker session: its coordination identity is its client id. */
const workerCtx = (ownerId: string) => ({
  ...baseCtx(), spawnId: ownerId, uiClientId: ownerId, isSuperuser: true, principal: null,
}) as unknown as UnifiedToolContext;

async function invoke(name: string, args: Record<string, unknown>, ctx: UnifiedToolContext): Promise<unknown> {
  const out = await dispatchProjectedToolToMcp(lookupByMcpName(name)!, name, args, ctx, {});
  if (out.isError) throw new Error((out.content?.[0] as { text?: string } | undefined)?.text ?? 'refused');
  return unwrapToolResult(out as ToolResult);
}

function wrapUp(callKey: string, segments: unknown, extra: Record<string, unknown> = {}) {
  return {
    harness: APP_HARNESS, operationId: 'call-wrap-up', requestKey: `wrap-up:${callKey}`,
    input: { callKey, transcriptRef: {
      segmentCount: Array.isArray(segments) ? segments.length : 0,
      sha256: segments === undefined ? '0'.repeat(64) : sha256(segments),
    } },
    ...(segments === undefined ? {} : { privateInput: segments }),
    ...extra,
  };
}

async function submit(args: Record<string, unknown>): Promise<BlueprintOperationHandle> {
  const out = await invoke(BLUEPRINT_OPERATION_TOOLS.submit, args, appCtx()) as { handle: BlueprintOperationHandle };
  return out.handle;
}

function itemId(handle: BlueprintOperationHandle): string {
  if (handle.target.kind !== 'work-item') throw new Error('expected a work-item target');
  return handle.target.id;
}

async function setItem(id: string, patch: { status?: string; holder?: string | null }): Promise<void> {
  if (patch.status !== undefined) {
    await db.sql`UPDATE harness_shared.work_items SET status = ${patch.status}
                  WHERE feature_id = ${id} AND workspace_id = ${WORKSPACE}`;
  }
  if (patch.holder !== undefined) {
    await db.sql`UPDATE harness_shared.work_items SET taken_by = ${patch.holder}
                  WHERE feature_id = ${id} AND workspace_id = ${WORKSPACE}`;
  }
}


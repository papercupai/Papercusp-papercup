describe('operation private input (D-014)', () => {
  it('preserves a reserved packet across recovery before acceptance and rejects a concurrent changed packet', async () => {
    const key = {
      workspaceId: WORKSPACE, harnessSlug: APP_HARNESS, callerId: APP_PRINCIPAL.slug,
      operationId: 'call-wrap-up', requestKey: 'wrap-up:reserved',
    };
    const altered: Segment[] = [[1, 'agent', 'A different frozen packet.']];
    const reserve = (value: unknown) => storeOperationPrivateInput(db.sql, key, {
      schema: SEGMENTS_SCHEMA, value, alreadyAccepted: false,
    });
    const attempts = await Promise.allSettled([reserve(SEGMENTS), reserve(altered)]);
    expect(attempts.filter((attempt) => attempt.status === 'fulfilled')).toHaveLength(1);
    const rejected = attempts.find((attempt) => attempt.status === 'rejected');
    expect(rejected?.status === 'rejected' && String(rejected.reason)).toContain('private_input_conflict');
    const [reserved] = await privateRows();
    const winner = JSON.parse(reserved!.content_text) as Segment[];
    const [{ n }] = await db.sql<Array<{ n: number }>>`SELECT count(*)::int AS n FROM harness_shared.work_items`;
    expect(n).toBe(0);
    // Simulate restarting after storage but before an acceptance receipt exists.
    const handle = await submit(wrapUp('reserved', winner));
    expect(await submit(wrapUp('reserved', winner))).toEqual(handle);
    expect(await privateRows()).toEqual([reserved]);
    await setItem(itemId(handle), { holder: HOLDER });
    expect((await readPrivate(HOLDER, itemId(handle))).content).toEqual(winner);
  });

  it('stores privateInput outside the work item, keyed by the invocation, hashed over JSON.stringify', async () => {
    const handle = await submit(wrapUp('call-1', SEGMENTS));
    const rows = await privateRows();
    expect(rows).toHaveLength(1);
    expect(rows[0]!.request_key).toBe('wrap-up:call-1');
    expect(rows[0]!.content_text).toBe(JSON.stringify(SEGMENTS));
    expect(rows[0]!.content_sha256).toBe(sha256(SEGMENTS));
    const [item] = await db.sql<Array<{ payload: unknown }>>`
      SELECT payload FROM harness_shared.work_items WHERE feature_id = ${itemId(handle)}`;
    expect(JSON.stringify(item!.payload)).not.toContain('confirming Tuesday');
  });

  it('replays an identical submit and refuses different content under the same key', async () => {
    const first = await submit(wrapUp('call-2', SEGMENTS));
    const replay = await submit(wrapUp('call-2', SEGMENTS));
    expect(replay).toEqual(first);
    expect(await privateRows()).toHaveLength(1);
    const altered: Segment[] = [[1, 'agent', 'Something else entirely.']];
    // Same key and same operation input (pinned ref), different private content.
    const args = { ...wrapUp('call-2', SEGMENTS), privateInput: altered };
    await expect(submit(args)).rejects.toThrow(/private_input_conflict/);
  });

  it('refuses privateInput to an undeclared operation, a missing one, and one failing the schema', async () => {
    await expect(submit({
      harness: APP_HARNESS, operationId: 'call-brief', requestKey: 'brief:1',
      input: { callKey: 'call-3' }, privateInput: SEGMENTS,
    })).rejects.toThrow(/invalid_request.*declares no privateInputSchema/);
    await expect(submit(wrapUp('call-3', undefined))).rejects.toThrow(/invalid_payload.*privateInput is required/);
    await expect(submit(wrapUp('call-3', [['only-two', 'fields']]))).rejects.toThrow(/invalid_payload/);
    await expect(submit(wrapUp('call-3', { segments: SEGMENTS }))).rejects.toThrow(/invalid_payload/);
    expect(await privateRows()).toHaveLength(0);
    const [{ n }] = await db.sql<Array<{ n: number }>>`SELECT count(*)::int AS n FROM harness_shared.work_items`;
    expect(n).toBe(0);
  });

  it('lets only the current holder of the non-terminal item read the exact content and sha256', async () => {
    const handle = await submit(wrapUp('call-4', SEGMENTS));
    const id = itemId(handle);
    await expect(readPrivate(HOLDER, id)).rejects.toThrow(/private_input_not_holder/);
    await setItem(id, { holder: HOLDER });
    const read = await readPrivate(HOLDER, id);
    expect(read.content).toEqual(SEGMENTS);
    expect(read.sha256).toBe(sha256(SEGMENTS));
    expect(read.operationId).toBe('call-wrap-up');
    await expect(readPrivate(OTHER, id)).rejects.toThrow(/private_input_not_holder/);
    await expect(readPrivate(HOLDER, 'WI-does-not-exist')).rejects.toThrow(/private_input_not_operation/);
    await setItem(id, { status: 'done' });
    await expect(readPrivate(HOLDER, id)).rejects.toThrow(/private_input_terminal/);
  });

  it('sweeps terminal and expired rows, keeps in-flight ones, and a later replay does not re-create them', async () => {
    const live = await submit(wrapUp('call-5', SEGMENTS));
    const done = await submit(wrapUp('call-6', SEGMENTS));
    const stale = await submit(wrapUp('call-7', SEGMENTS));
    await setItem(itemId(done), { status: 'done' });
    await db.sql`UPDATE harness_shared.blueprint_operation_private_inputs
                    SET expires_at = now() - interval '1 minute' WHERE request_key = 'wrap-up:call-7'`;
    const swept = await pruneOperationPrivateInputs({ sql: db.sql });
    expect(swept.deleted).toBe(2);
    expect((await privateRows()).map((row) => row.request_key)).toEqual(['wrap-up:call-5']);
    // A replay of the accepted-and-swept operation returns its handle and stores nothing.
    expect(await submit(wrapUp('call-6', SEGMENTS))).toEqual(done);
    expect((await privateRows()).map((row) => row.request_key)).toEqual(['wrap-up:call-5']);
    // An expired row is unreadable even before the sweep would reach it.
    await setItem(itemId(stale), { holder: HOLDER });
    await expect(readPrivate(HOLDER, itemId(stale))).rejects.toThrow(/private_input_absent/);
    await setItem(itemId(live), { holder: HOLDER });
    expect((await readPrivate(HOLDER, itemId(live))).sha256).toBe(sha256(SEGMENTS));
  });
});

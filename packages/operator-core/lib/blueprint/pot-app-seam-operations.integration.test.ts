async function settle(handle: BlueprintOperationHandle, write: { status: string; output?: unknown }): Promise<void> {
  if (handle.target.kind !== 'work-item') throw new Error('expected a direct work-item target');
  const payload = write.output === undefined ? {} : { blueprintResult: {
    operationId: handle.operationId, specificationRevision: handle.specificationRevision,
    output: write.output, evidenceRef: 'verification:pot-app-seam-operations',
  } };
  await db.sql`
    UPDATE harness_shared.work_items
       SET status = ${write.status}, authority = 'committed',
           payload = payload || ${JSON.stringify(payload)}::text::jsonb
     WHERE feature_id = ${handle.target.id} AND workspace_id = ${WORKSPACE} AND harness_slug = ${APP_HARNESS}`;
}

/** Minimal check of an output against the declared resultSchema (required + types + no extras). */
function satisfiesDeclaredResult(output: unknown): boolean {
  if (!output || typeof output !== 'object' || Array.isArray(output)) return false;
  const record = output as Record<string, unknown>;
  const props = DRAFT_RESULT_SCHEMA.properties as Record<string, { type: string }>;
  return DRAFT_RESULT_SCHEMA.required.every((k) => typeof record[k] === props[k].type) &&
    Object.keys(record).every((k) => k in props);
}

type DraftOutput = { draftId: string; body: string };

/** The app's own parse gate: stricter than the declared schema (an empty body is not a draft). */
function parseDraft(output: unknown): DraftOutput {
  if (!satisfiesDeclaredResult(output)) throw new Error('draft output does not satisfy the declared resultSchema');
  const draft = output as DraftOutput;
  if (draft.body.trim() === '') throw new Error('an empty draft body is not a usable reply');
  return draft;
}

async function workItemCount(): Promise<number> {
  const rows = await db.sql<Array<{ n: number }>>`SELECT count(*)::int AS n FROM harness_shared.work_items`;
  return rows[0].n;
}

describe('R-2 pot-app-seam operation client (D-001)', () => {
  it('calls exactly the seven public blueprint:* tools the R-1 contract pins', () => {
    expect(BLUEPRINT_OPERATION_TOOL_NAMES).toEqual(BLUEPRINT_OPERATION_TOOLS);
  });

  describe.each(['http', 'mcp'] as const)('over %s', (transport) => {
    it('replays one execution per request key and refuses the same key with different input', async () => {
      const seam = appSeam(transport);
      const [first] = await seam.submitOperations([draftFor('thr-1')]);
      const minted = await workItemCount();
      expect(minted).toBeGreaterThan(0);

      const [replayed] = await seam.submitOperations([draftFor('thr-1')]);
      expect(replayed).toEqual(first);
      expect(await workItemCount()).toBe(minted);

      await expect(seam.submitOperations([draftFor('thr-1', 'formal')])).rejects.toThrow();
      expect(await workItemCount()).toBe(minted);

      // Positive control: a different domain key is a different request and DOES mint.
      const [other] = await seam.submitOperations([draftFor('thr-2')]);
      expect(other.receiptId).not.toBe(first.receiptId);
      expect(await workItemCount()).toBeGreaterThan(minted);
    });

    it('reads and pages the operation events through the seam', async () => {
      const seam = appSeam(transport);
      const [handle] = await seam.submitOperations([draftFor('thr-ev')]);
      await seam.cancelOperation(handle, { requestKey: deriveRequestKey('cancel', 'thr-ev'), reason: 'thread archived' });

      const page = await seam.operationEvents(handle, { limit: 50 });
      expect(page.status).toMatchObject({ cancellationRequested: true });
      expect(page.events.map((e) => e.kind)).toContain('cancel');
      for (const event of page.events) expect(typeof event.cursor).toBe('string');

      const resumed = await seam.operationEvents(handle, { cursor: page.cursor });
      expect(resumed.events).toEqual([]);
      expect(resumed.hasMore).toBe(false);
    });

    it('records a cancel; once honoured the operation ends cancelled and the parse gate never runs', async () => {
      const seam = appSeam(transport);
      const [handle] = await seam.submitOperations([draftFor('thr-cancel')]);
      const cancelKey = deriveRequestKey('cancel', 'thr-cancel');
      const receipt = await seam.cancelOperation(handle, { requestKey: cancelKey, reason: 'thread archived' });
      expect(receipt).toMatchObject({ accepted: true, replayed: false });
      expect(await seam.operationStatus(handle)).toMatchObject({ cancellationRequested: true });
      expect(await seam.cancelOperation(handle, { requestKey: cancelKey, reason: 'thread archived' }))
        .toMatchObject({ eventId: receipt.eventId, replayed: true });

      await settle(handle, { status: 'dropped' });
      const parse = vi.fn(parseDraft);
      const result = await seam.operationResult(handle, parse);
      expect(result.state).toBe('cancelled');
      expect(result).not.toHaveProperty('output');
      expect(parse).not.toHaveBeenCalled();
    });

    it('lets a ready output reach the app only through its parse gate', async () => {
      const seam = appSeam(transport);
      const [handle] = await seam.submitOperations([draftFor('thr-ok')]);
      expect((await seam.operationResult(handle, parseDraft)).state).toBe('pending');

      await settle(handle, { status: 'passed', output: { draftId: 'draft-1', body: 'Thanks — confirming Tuesday.' } });
      expect(await seam.operationResult(handle, parseDraft))
        .toMatchObject({ state: 'ready', output: { draftId: 'draft-1', body: 'Thanks — confirming Tuesday.' } });

      // Schema-valid for the operator, rejected by the app's gate: nothing of it reaches the caller.
      const [blank] = await seam.submitOperations([draftFor('thr-blank')]);
      await settle(blank, { status: 'passed', output: { draftId: 'draft-2', body: '   ' } });
      await expect(seam.operationResult(blank, parseDraft)).rejects.toBeInstanceOf(OperationOutputRejectedError);
    });
  });
});

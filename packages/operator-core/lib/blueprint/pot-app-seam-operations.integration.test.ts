/**
 * R-2 / P-002 (plan app-agent-tasks-durable-execution-2026-10-06, D-001) — the
 * pot-app-seam operation client against the REAL public blueprint:* tools.
 *
 * Apps reach agent work only through `@papercusp/pot-app-seam`. This suite builds
 * the seam the way an app host does — `createPotAppSeam` over
 * `blueprintOperationHostFromInvoker` — and drives it through real projected
 * dispatch on HTTP and MCP against a fresh PostgreSQL (fixture shared with the R-1
 * contract suite). It proves, per transport:
 *   • a resubmitted request key replays the original handle and mints no second
 *     execution (positive control: a different domain key DOES mint one), and the
 *     same key with different input is refused;
 *   • the operation's events are readable and pageable through the seam;
 *   • a cancel through the seam is recorded, and once the executor honours it the
 *     operation ends `cancelled` with no ready result — the parse gate never runs;
 *   • a `ready` output reaches the app only through its parse gate, and an output
 *     the gate rejects throws `OperationOutputRejectedError`.
 *
 * Settlement (the executor's durable write) is simulated exactly as in R-1.
 */

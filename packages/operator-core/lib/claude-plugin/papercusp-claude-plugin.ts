/**
 * The `papercusp` Claude Code plugin — generated from the hook-enrollment source,
 * installed as a settings-enrolled directory marketplace, and the ONLY carrier of
 * the papercusp Claude hooks once installed.
 * client-native-features-adoption-2026-10-21 P-004, decision D-012.
 *
 * Source of truth: the plugin's hooks are `mergeClaudeHookSettings({}, hookDir, { present }).hooks`
 * (see `papercuspClaudePluginHooks` in desktop-install/papercusp-files.ts), the same function that
 * enrolled them inline in ~/.claude/settings.json before. The commands still point at the installed
 * ~/.papercusp/hooks/cc scripts, so only the carrier changes; the scripts do not.
 *
 * Layout written under the marketplace root (default ~/.papercusp/claude-plugins):
 *   .claude-plugin/marketplace.json            marketplace `papercusp-local`
 *   plugins/papercusp/.claude-plugin/plugin.json
 *   plugins/papercusp/hooks/hooks.json         { hooks }
 *
 * Measured on claude 2.1.293 (D-012): the plugin is read from this source folder on every launch
 * (not from a cache copy), so regenerating in place is enough; a settings-only enrollment loads it
 * without `claude plugin install`; and a command enrolled both inline and in the plugin fires twice,
 * so `stripPluginCarriedInlineHooks` removes the inline copy of every command the plugin carries.
 * statusLine and enableAllProjectMcpServers stay inline: a plugin cannot carry them.
 */
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';

import {
  PAPERCUSP_CLAUDE_MARKETPLACE_NAME,
  PAPERCUSP_CLAUDE_PLUGIN_HOOKS_RELPATH,
  PAPERCUSP_CLAUDE_PLUGIN_ID,
  PAPERCUSP_CLAUDE_PLUGIN_NAME,
  PAPERCUSP_CLAUDE_PLUGIN_SUBDIR,
  enrollPapercuspClaudePlugin,
  stripPluginCarriedInlineHooks,
  type ClaudeHookMap,
} from './plugin-rails.mjs';

export {
  PAPERCUSP_CLAUDE_MARKETPLACE_NAME,
  PAPERCUSP_CLAUDE_PLUGIN_HOOKS_RELPATH,
  PAPERCUSP_CLAUDE_PLUGIN_ID,
  PAPERCUSP_CLAUDE_PLUGIN_NAME,
};
export type { ClaudeHookMap };
export { enrollPapercuspClaudePlugin, stripPluginCarriedInlineHooks };

/** Marketplace root for a given home directory. */
export function papercuspClaudePluginRoot(home: string): string {
  return path.join(home, '.papercusp', 'claude-plugins');
}

export interface PapercuspClaudePlugin {
  /** The hooks the plugin carries (a deep copy of the input). */
  hooks: ClaudeHookMap;
  /** File contents keyed by path relative to the marketplace root. */
  files: Record<string, string>;
}

const DESCRIPTION =
  'Papercusp coordination hooks (file locks, activity reporting, coord delivery, guards). ' +
  'Generated by the Papercusp installer from the hook-enrollment source; do not edit.';

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/** Build the plugin's files from a hooks map. Pure. */
export function buildPapercuspClaudePlugin(hooks: ClaudeHookMap): PapercuspClaudePlugin {
  const copy = JSON.parse(JSON.stringify(hooks ?? {})) as ClaudeHookMap;
  const author = { name: 'Papercusp' };
  const marketplace = {
    name: PAPERCUSP_CLAUDE_MARKETPLACE_NAME,
    owner: author,
    description: 'Local marketplace holding the generated papercusp plugin.',
    plugins: [{ name: PAPERCUSP_CLAUDE_PLUGIN_NAME, source: `./${PAPERCUSP_CLAUDE_PLUGIN_SUBDIR}`, description: DESCRIPTION }],
  };
  const manifest = { name: PAPERCUSP_CLAUDE_PLUGIN_NAME, version: '1.0.0', description: DESCRIPTION, author };
  return {
    hooks: copy,
    files: {
      '.claude-plugin/marketplace.json': json(marketplace),
      [`${PAPERCUSP_CLAUDE_PLUGIN_SUBDIR}/.claude-plugin/plugin.json`]: json(manifest),
      [PAPERCUSP_CLAUDE_PLUGIN_HOOKS_RELPATH]: json({ hooks: copy }),
    },
  };
}

/** Write every plugin file under `root` (atomic per file: tmp + rename). */
export async function writePapercuspClaudePlugin(root: string, plugin: PapercuspClaudePlugin): Promise<void> {
  for (const [rel, text] of Object.entries(plugin.files)) {
    const dest = path.join(root, rel);
    await mkdir(path.dirname(dest), { recursive: true });
    const tmp = `${dest}.tmp-${process.pid}-${Date.now()}`;
    await writeFile(tmp, text, 'utf8');
    await rename(tmp, dest);
  }
}

export interface PapercuspClaudePluginDrift {
  /** `in-sync`: every file matches; `missing`: a file is absent; `drift`: a file differs. */
  status: 'in-sync' | 'missing' | 'drift';
  /** Relative paths that are missing or differ. */
  files: string[];
}

/** Compare the plugin on disk with a fresh build. A difference means the installed rails no longer
 *  match the enrollment source. */
export async function detectPapercuspClaudePluginDrift(
  root: string,
  plugin: PapercuspClaudePlugin,
): Promise<PapercuspClaudePluginDrift> {
  const missing: string[] = [];
  const differing: string[] = [];
  for (const [rel, expected] of Object.entries(plugin.files)) {
    let actual: string;
    try {
      actual = await readFile(path.join(root, rel), 'utf8');
    } catch {
      missing.push(rel);
      continue;
    }
    if (actual !== expected) differing.push(rel);
  }
  if (missing.length > 0) return { status: 'missing', files: [...missing, ...differing] };
  if (differing.length > 0) return { status: 'drift', files: differing };
  return { status: 'in-sync', files: [] };
}

export interface PapercuspClaudePluginCarrierResult {
  /** True when the plugin was written, verified and enrolled, and the inline copies removed. */
  ok: boolean;
  root: string;
  /** Inline commands removed because the plugin now carries them. */
  removedInline: number;
  /** Why the plugin could not become the carrier; the inline enrollment is then left in place. */
  error?: string;
}

/**
 * Make the plugin the carrier for `hooks` in a settings object (mutated in place): write the plugin
 * under `root`, verify it reads back identical, enroll it, then strip the inline copies. If writing
 * or verifying fails, `cfg` is not touched, so the inline enrollment stays and the session is never
 * left with no carrier at all.
 */
export async function applyPapercuspClaudePluginCarrier(opts: {
  cfg: Record<string, any>;
  hooks: ClaudeHookMap;
  root: string;
}): Promise<PapercuspClaudePluginCarrierResult> {
  const plugin = buildPapercuspClaudePlugin(opts.hooks);
  try {
    await writePapercuspClaudePlugin(opts.root, plugin);
    const drift = await detectPapercuspClaudePluginDrift(opts.root, plugin);
    if (drift.status !== 'in-sync') {
      throw new Error(`plugin read back ${drift.status}: ${drift.files.join(', ')}`);
    }
  } catch (e) {
    return { ok: false, root: opts.root, removedInline: 0, error: e instanceof Error ? e.message : String(e) };
  }
  enrollPapercuspClaudePlugin(opts.cfg, opts.root);
  const removedInline = stripPluginCarriedInlineHooks(opts.cfg, plugin.hooks);
  return { ok: true, root: opts.root, removedInline };
}

/**
 * store.integration.test.ts — the deferral-interest model store
 * (deferral_pricing_model, migration 252), against a real Postgres. Injectable sql.
 *
 * Behaviors a fake-sql unit test can't prove:
 *  - saveDeferralModel is APPEND-ONLY (each fit is a new version; never overwrites)
 *    and stores the model as a jsonb OBJECT (::text::jsonb);
 *  - loadLatestDeferralModel returns the newest by trained_at;
 *  - the STRUCTURAL GUARD: a junk/malformed model row degrades to null (never
 *    throws a bad model into the ranker) — isDeferralPricingModel on the way out.
 */
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import postgres from 'postgres';
import { randomBytes } from 'node:crypto';
import { getTestPg, markManagedTestDatabase } from '@papercusp/test-config/pg';

const { saveDeferralModel, loadLatestDeferralModel } = await import('./store');

const WS = 'ws-defer';
let rootSql: postgres.Sql;
const model = (over: Record<string, unknown> = {}) =>
  ({ version: 1, trainedAt: '2026-01-01T00:00:00Z', globalRatePerWeek: 1.5, totalItems: 10, totalWeeks: 20, priorWeeks: 4, weak: false, buckets: { a: { factor: 1 } }, ...over }) as never;

beforeAll(async () => {
  const adminUri = await getTestPg();
  const dbName = `defer_${randomBytes(5).toString('hex')}`;
  const admin = postgres(adminUri, { max: 1, onnotice: () => {} });
  try {
    await admin.unsafe(`CREATE DATABASE "${dbName}"`);
    await markManagedTestDatabase(admin, dbName);
  } finally {
    await admin.end({ timeout: 5 });
  }
  const u = new URL(adminUri);
  u.pathname = `/${dbName}`;
  rootSql = postgres(u.toString(), { max: 1, onnotice: () => {} });
  await rootSql.unsafe(`CREATE SCHEMA harness_shared`);
  await rootSql.unsafe(`
    CREATE TABLE harness_shared.deferral_pricing_model (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id text NOT NULL,
      trained_at timestamptz NOT NULL DEFAULT now(),
      model jsonb NOT NULL,
      sample_items integer NOT NULL,
      sample_weeks numeric NOT NULL,
      created_by text,
      CONSTRAINT deferral_pricing_model_workspace_nonempty CHECK (workspace_id <> ''),
      CONSTRAINT deferral_pricing_model_items_nonneg CHECK (sample_items >= 0)
    )`);
}, 90_000);

afterAll(async () => {
  await rootSql?.end({ timeout: 5 });
});

beforeEach(async () => {
  await rootSql`TRUNCATE harness_shared.deferral_pricing_model RESTART IDENTITY`;
});

describe('deferral-interest model store (PG)', () => {
  it('saveDeferralModel stores a jsonb-object model; loadLatest reads it back', async () => {
    await saveDeferralModel(rootSql, WS, model({ globalRatePerWeek: 2.5 }));
    expect(await loadLatestDeferralModel(rootSql, WS)).toMatchObject({ version: 1, globalRatePerWeek: 2.5, totalItems: 10 });
    expect((await rootSql`SELECT jsonb_typeof(model) AS t FROM harness_shared.deferral_pricing_model`)[0]!.t).toBe('object');
  });

  it('is APPEND-ONLY: each save is a new version; loadLatest returns the newest trained_at', async () => {
    await saveDeferralModel(rootSql, WS, model({ trainedAt: '2026-01-01T00:00:00Z', globalRatePerWeek: 1 }));
    await saveDeferralModel(rootSql, WS, model({ trainedAt: '2026-06-01T00:00:00Z', globalRatePerWeek: 9 }));
    expect(await rootSql`SELECT 1 FROM harness_shared.deferral_pricing_model`).toHaveLength(2); // both kept
    expect((await loadLatestDeferralModel(rootSql, WS))!.globalRatePerWeek).toBe(9); // newest wins
  });

  it('STRUCTURAL GUARD: a junk model row degrades to null (never throws into the ranker)', async () => {
    // a malformed model jsonb, with the newest trained_at so it would be "latest"
    await rootSql`INSERT INTO harness_shared.deferral_pricing_model (workspace_id, trained_at, model, sample_items, sample_weeks)
                  VALUES (${WS}, '2027-01-01T00:00:00Z', ${rootSql.json({ corrupt: true })}, 0, 0)`;
    expect(await loadLatestDeferralModel(rootSql, WS)).toBeNull(); // not the junk object
  });

  it('loadLatest is workspace-scoped and null when none', async () => {
    expect(await loadLatestDeferralModel(rootSql, 'empty-ws')).toBeNull();
    await saveDeferralModel(rootSql, 'other-ws', model());
    expect(await loadLatestDeferralModel(rootSql, WS)).toBeNull(); // other-ws's model invisible to WS
  });
});

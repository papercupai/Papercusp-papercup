/**
 * delegated-tasks.integration.test.ts — the collapse-delegate-into-workitems
 * mechanism end-to-end against real PG (migrations 131 + 142 + 152).
 *
 * Verifies the plan's load-bearing claims:
 *   • D-001 — a delegated task IS a work_item: createDelegatedTask mints a kind=task
 *     issue-family item, operator-scoped, assigned to the delegate session, assigned_by
 *     the operator, with the resume metadata in payload.
 *   • the issues:* surface is NOT polluted — listIssues (default bug|change) excludes
 *     tasks; work_items:list { assignedBy, kind:'task' } finds them.
 *   • D-003 — subscribe→inject (REAL fan-out, not a spy): a recorded turn fans the
 *     completion out to the operator's coord inbox (the operator auto-subscribed as
 *     creator; the turn is authored AS the delegate so the operator is NOT excluded).
 *   • the session-shaped projection (list/get/search/archive) used by the panel + voice.
 *   • resume — findOpenDelegatedTask resolves an open task by session id; resolving it
 *     (→done) takes it out of the open set.
 *   • the operator-hindsight channel — notify → drain (once) → re-drain empty (the
 *     voice-scoped ack makes it non-replaying).
 */

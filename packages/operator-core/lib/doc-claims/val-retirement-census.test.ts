/**
 * P-003 source census — the VAL-* assertion store is retired
 * (plan verification-system-improvements-2026-10-10; AUTO-BAR-R-3-P-003,
 * SPEC-P-003-VAL-READERS, SPEC-P-003-VAL-WRITERS).
 *
 * Bar: no non-test source file reads or writes `harness_plan_assertions`. The
 * requirement contract (plan_spec_clauses + bound evidence) is the successor; every
 * former writer returns the typed `ValRetirementRefusalCode` refusal from
 * `../agent-tools/plans/val-retirement.ts` instead.
 *
 * How the census measures:
 *  - Enumeration is `git grep --recurse-submodules` over TRACKED files only. Untracked
 *    `dist/` bundles also carry the strings, and they are not source.
 *  - Each candidate is re-judged on `stripCommentsOnly` text. Comments are dropped,
 *    STRING LITERALS ARE KEPT: the table name lives inside SQL template literals, so
 *    stripping strings would turn every real read into a silent false negative
 *    (CLAUDE.md "Proving a guard is falsifiable", source-tree tier).
 *  - Two instruments are proven on every run, so an empty violation list cannot be
 *    vacuous: (1) the detector flags a string-literal SQL read and a drizzle reference,
 *    and ignores a comment-only mention; (2) the enumeration reaches into the
 *    `libs/papercusp` submodule (the generated drizzle schema must still be found).
 */
import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripCommentsOnly } from '../../../../scripts/lib/strip-comments-and-strings.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');

/** Every live spelling of the retired store: SQL name, drizzle export, sync query name. */
export const VAL_STORE_TOKENS = [
  'harness_plan_assertions',
  'harnessPlanAssertions',
  'assertionsByHarness',
] as const;

const TOKEN_RE = new RegExp(`\\b(${VAL_STORE_TOKENS.join('|')})\\b`, 'g');

const SOURCE_GLOBS = ['*.ts', '*.tsx', '*.mts', '*.cts', '*.js', '*.mjs', '*.cjs'];

/** Test code may name the store (fixtures, these controls); the bar is about source. */
const TEST_PATH_RE = /(\.(test|spec)\.[cm]?[jt]sx?$)|(\/__tests__\/)|(\/__fixtures__\/)/;

/**
 * Files that DESCRIBE the table without reading or writing it. Shrink-only: an entry
 * that stops matching fails the census so it is removed, not left to rot.
 */
const DESCRIPTIVE_ALLOWLIST: Record<string, string> = {
  'libs/papercusp/libs/db/src/schema/generated.ts':
    'pull-schema output declaring the table that still exists in Postgres; a declaration, not a read or write. Removed when a migration drops the table.',
  'packages/operator-core/lib/db-schema-reference/index-manifest.ts':
    'GENERATED fresh-install index census (schema-object-drift reference); names the pkey index, never queries it.',
};

/** Tracked build outputs regenerated from the sources this census already judges. */
const BUILD_OUTPUT_PREFIXES: Record<string, string> = {
  'papercusp-desktop/src-tauri/env-sidecars/':
    '@generated by apps/operator/bin/bundle-host.sh (and its Vite SPA assets); rebuilt from apps/operator + packages sources.',
};

export interface ValStoreHit {
  token: string;
  line: number;
}

/** Live (non-comment) references to the retired store in one file's text. */
export function findLiveValStoreRefs(text: string, fileName: string): ValStoreHit[] {
  const live: string = stripCommentsOnly(text, fileName);
  const hits: ValStoreHit[] = [];
  for (const m of live.matchAll(TOKEN_RE)) {
    const line = live.slice(0, m.index).split('\n').length;
    hits.push({ token: m[1], line });
  }
  return hits;
}

/** Tracked source files (superproject + submodules) whose raw text names the store. */
function trackedCandidates(): string[] {
  try {
    const out = execFileSync(
      'git',
      [
        'grep',
        '-l',
        '-I',
        '--recurse-submodules',
        '-E',
        VAL_STORE_TOKENS.join('|'),
        '--',
        ...SOURCE_GLOBS,
      ],
      { cwd: ROOT, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
    );
    return out.split('\n').filter(Boolean);
  } catch (err) {
    // git grep exits 1 when nothing matches; anything else is a broken instrument.
    const e = err as { status?: number; stdout?: string };
    if (e.status === 1) return [];
    throw err;
  }
}

describe('P-003 census: no non-test source reads or writes the retired VAL-* store', () => {
  it('detector control: keeps string literals, drops comments', () => {
    const sqlRead = [
      'export async function rows(sql) {',
      '  return sql`SELECT * FROM harness_shared.harness_plan_assertions WHERE harness_slug = ${"h"}`;',
      '}',
    ].join('\n');
    const drizzle = 'export const q = db.select().from(harnessPlanAssertions);';
    const syncName = "registry.register('assertionsByHarness', resolver);";
    const commentOnly = [
      '// The legacy harness_plan_assertions table is retired (P-003).',
      '/* assertionsByHarness was its sync query. */',
      'export const ok = 1;',
    ].join('\n');

    expect(findLiveValStoreRefs(sqlRead, 'a.ts').map((h) => h.token)).toEqual([
      'harness_plan_assertions',
    ]);
    expect(findLiveValStoreRefs(sqlRead, 'a.ts')[0].line).toBe(2);
    expect(findLiveValStoreRefs(drizzle, 'b.ts')).toHaveLength(1);
    expect(findLiveValStoreRefs(syncName, 'c.ts')).toHaveLength(1);
    expect(findLiveValStoreRefs(commentOnly, 'd.ts')).toEqual([]);
  });

  it('enumeration control: reaches into the libs/papercusp submodule', () => {
    const candidates = trackedCandidates();
    expect(candidates).toContain('libs/papercusp/libs/db/src/schema/generated.ts');
  });

  it('no non-test tracked source file references the store in live code', () => {
    const violations: string[] = [];
    const allowlistSeen = new Set<string>();

    for (const rel of trackedCandidates()) {
      if (TEST_PATH_RE.test(rel)) continue;
      if (Object.keys(BUILD_OUTPUT_PREFIXES).some((p) => rel.startsWith(p))) continue;
      const hits = findLiveValStoreRefs(readFileSync(join(ROOT, rel), 'utf8'), rel);
      if (hits.length === 0) continue;
      if (rel in DESCRIPTIVE_ALLOWLIST) {
        allowlistSeen.add(rel);
        continue;
      }
      for (const h of hits) violations.push(`${rel}:${h.line} ${h.token}`);
    }

    expect(
      violations,
      'Retire these per WI-6554700010008355: a writer returns valRetirementRefusal(...), a reader is removed (successor: the requirement contract).',
    ).toEqual([]);

    const staleAllowlist = Object.keys(DESCRIPTIVE_ALLOWLIST).filter((p) => !allowlistSeen.has(p));
    expect(staleAllowlist, 'Allowlist entries that no longer match: remove them.').toEqual([]);
  });
});

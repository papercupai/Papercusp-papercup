/**
 * Codex hook bridge for an in-container Codex arm (benchmark-coverage-frontierswe-v2-2026-10-10 D-032).
 *
 * The operator writes the session's Codex hooks into `$CODEX_HOME/hooks.json` as HOST commands (scripts under
 * ~/.papercusp/hooks that call the operator on 127.0.0.1). When Codex runs inside a task container, Codex would
 * spawn those commands inside the container, where they do not exist, and Codex reports any hook failure as a bare
 * `hook: <Event> Failed` and carries on. So every hook would silently stop working.
 *
 * This module keeps the hooks on the HOST:
 *   - {@link renderHookShim}: a fixed POSIX script, mounted read-only into the container. Its shebang is the host's
 *     STATIC busybox (also mounted read-only), so it works on any task image. It POSTs the hook payload to the
 *     bridge and reproduces the host hook's stdout, stderr and exit code exactly. If the bridge is unreachable it
 *     exits 2 with the reason on stderr.
 *   - {@link startCodexHookBridge}: one loopback HTTP server per run, exposed to task containers as a bench-egress
 *     endpoint. It runs command <index> of a session's TRUSTED record with the payload on stdin.
 *   - The trusted record is written by the docker-exec wrapper (container-exec-target.ts) into a host-only dir that
 *     is never mounted, while the session dir is still invisible to every container. The container can neither
 *     read another session's token nor change which host command an index runs.
 */
import { spawn } from 'node:child_process';
import { timingSafeEqual } from 'node:crypto';
import { chmodSync, closeSync, mkdirSync, mkdtempSync, openSync, readFileSync, readSync, writeFileSync } from 'node:fs';
import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

/** Where the shim is mounted read-only inside the task container. */
export const CONTAINER_HOOK_SHIM_PATH = '/opt/papercusp/hook-shim';
/** Where the host's static busybox is mounted read-only inside the task container (the shim's interpreter). */
export const CONTAINER_BUSYBOX_PATH = '/opt/papercusp/busybox';
/** The host's statically linked busybox (Ubuntu `busybox` package; measured static on the bench host, D-032). */
export const HOST_STATIC_BUSYBOX = '/usr/bin/busybox';
/** The bench-egress endpoint name the bridge is exposed under. */
export const HOOK_BRIDGE_ENDPOINT = 'hooks';

/** One session's trusted hook commands, in the order the shimmed hooks.json refers to them by index. */
export interface HookRecord {
  session: string;
  token: string;
  commands: { event: string; command: string; timeoutSec?: number }[];
}

/** Session names are path components of the record dir: refuse anything that could traverse out of it. */
export const HOOK_SESSION_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/;
const TOKEN = /^[0-9a-f]{32}$/;

/** The shim. Usage inside the container: `hook-shim <bridgeUrl> <session> <token> <index|ping>`, payload on stdin. */
export function renderHookShim(): string {
  return `#!${CONTAINER_BUSYBOX_PATH} sh
# Generated by papercusp external-bench/codex-hook-bridge.ts (benchmark-coverage-frontierswe-v2 D-032). Do not edit.
# Runs one Papercusp Codex hook on the HOST through the hook bridge; exits with the host hook's own exit code.
B=${CONTAINER_BUSYBOX_PATH}
if [ "$#" -ne 4 ]; then echo "papercusp hook-shim: usage: hook-shim <url> <session> <token> <index|ping>" >&2; exit 2; fi
d=$($B mktemp -d) || { echo "papercusp hook-shim: mktemp failed" >&2; exit 2; }
trap '$B rm -rf "$d"' EXIT
$B cat > "$d/in"
if ! $B wget -q -T 900 -O "$d/out" --header 'Content-Type: application/octet-stream' --post-file="$d/in" "$1/hook/$2/$3/$4" 2>"$d/err"; then
  echo "papercusp hook bridge unreachable at $1: $($B cat "$d/err")" >&2
  exit 2
fi
code=$($B sed -n 1p "$d/out")
case "$code" in ''|*[!0-9]*) echo "papercusp hook bridge: malformed reply" >&2; exit 2;; esac
$B sed -n 2p "$d/out" | $B base64 -d
$B sed -n 3p "$d/out" | $B base64 -d >&2
exit "$code"
`;
}

/** Write the shim as an executable file in `dir` (default: a fresh temp dir) and return its path. */
export function materializeHookShim(dir?: string): string {
  const d = dir ?? mkdtempSync(join(tmpdir(), 'papercusp-hookshim-'));
  mkdirSync(d, { recursive: true });
  const p = join(d, 'hook-shim');
  writeFileSync(p, renderHookShim(), { mode: 0o755 });
  chmodSync(p, 0o755);
  return p;
}

/**
 * True when `path` is an ELF executable with no PT_INTERP program header, i.e. it needs no dynamic loader and so
 * runs inside any container image. Reads only the ELF header and the program header table.
 */
export function isStaticElf(path: string): boolean {
  let fd: number;
  try {
    fd = openSync(path, 'r');
  } catch {
    return false;
  }
  try {
    const head = Buffer.alloc(64);
    if (readSync(fd, head, 0, 64, 0) < 64) return false;
    if (head.readUInt32BE(0) !== 0x7f454c46) return false; // \x7fELF
    if (head[4] !== 2 || head[5] !== 1) return false; // 64-bit, little-endian (the bench host)
    const phoff = Number(head.readBigUInt64LE(32));
    const phentsize = head.readUInt16LE(54);
    const phnum = head.readUInt16LE(56);
    if (phnum === 0 || phentsize < 4) return false;
    const table = Buffer.alloc(phentsize * phnum);
    if (readSync(fd, table, 0, table.length, phoff) < table.length) return false;
    for (let i = 0; i < phnum; i++) if (table.readUInt32LE(i * phentsize) === 3) return false; // PT_INTERP
    return true;
  } finally {
    closeSync(fd);
  }
}

/** The host busybox to mount as the shim's interpreter. Throws (fail closed) unless it is a static ELF. */
export function resolveStaticBusybox(path: string = process.env.PAPERCUSP_BENCH_STATIC_BUSYBOX || HOST_STATIC_BUSYBOX): string {
  if (!isStaticElf(path)) {
    throw new Error(
      `codex hook bridge: ${path} is not a statically linked ELF busybox — an in-container Codex arm cannot run its hooks without one (D-032). Install the busybox package or set PAPERCUSP_BENCH_STATIC_BUSYBOX.`,
    );
  }
  return path;
}

export function hookRecordPath(recordDir: string, session: string): string {
  if (!HOOK_SESSION_NAME.test(session)) throw new Error(`codex hook bridge: bad session name ${JSON.stringify(session)}`);
  return join(recordDir, `${session}.json`);
}

/** Read a session's trusted record, or null when it does not exist / is malformed. */
export function readHookRecord(recordDir: string, session: string): HookRecord | null {
  let raw: string;
  try {
    raw = readFileSync(hookRecordPath(recordDir, session), 'utf8');
  } catch {
    return null;
  }
  try {
    const r = JSON.parse(raw) as HookRecord;
    if (r.session !== session || typeof r.token !== 'string' || !TOKEN.test(r.token) || !Array.isArray(r.commands)) return null;
    return r;
  } catch {
    return null;
  }
}

function tokenMatches(expected: string, given: string): boolean {
  const a = Buffer.from(expected);
  const b = Buffer.from(given);
  return a.length === b.length && timingSafeEqual(a, b);
}

export interface HookBridgeStats {
  calls: number;
  pings: number;
  refused: number;
  failed: number;
}

export interface CodexHookBridge {
  /** Loopback port; the bench-egress `hooks` endpoint's targetPort. */
  readonly port: number;
  readonly recordDir: string;
  stats(): HookBridgeStats;
  /** Close the server; in-flight hook processes are killed. Idempotent. */
  stop(): Promise<void>;
}

export interface CodexHookBridgeConfig {
  /** Host-only dir the wrapper writes trusted records into. Must never be mounted into a container. */
  recordDir: string;
  /** Per-hook timeout when the record carries none. Default 600s (Codex's own default hook timeout). */
  defaultTimeoutSec?: number;
  /** Request body cap. Default 32 MiB (PostToolUse payloads carry the tool output). */
  maxBodyBytes?: number;
  /** Env for the host hook processes. Default: PATH, HOME, USER, LANG of this process (hook commands bake the rest). */
  env?: NodeJS.ProcessEnv;
}

function minimalEnv(): NodeJS.ProcessEnv {
  const out: NodeJS.ProcessEnv = {};
  for (const k of ['PATH', 'HOME', 'USER', 'LOGNAME', 'LANG', 'TMPDIR']) if (process.env[k]) out[k] = process.env[k];
  return out;
}

/** SIGKILL a hook's whole process group (its pid is the group id, see `setsid` above), then the child itself. */
function killTree(child: ReturnType<typeof spawn>): void {
  if (child.pid) {
    try {
      process.kill(-child.pid, 'SIGKILL');
    } catch {
      /* already gone */
    }
  }
  child.kill('SIGKILL');
}

const reply = (res: ServerResponse, status: number, code: number, stdout: Buffer | string, stderr: Buffer | string) => {
  res.writeHead(status, { 'Content-Type': 'text/plain' });
  res.end(`${code}\n${Buffer.from(stdout).toString('base64')}\n${Buffer.from(stderr).toString('base64')}\n`);
};

/** Start the run's hook bridge on 127.0.0.1 (ephemeral port). */
export async function startCodexHookBridge(cfg: CodexHookBridgeConfig): Promise<CodexHookBridge> {
  const recordDir = cfg.recordDir;
  mkdirSync(recordDir, { recursive: true, mode: 0o700 });
  chmodSync(recordDir, 0o700);
  const defaultTimeoutSec = cfg.defaultTimeoutSec ?? 600;
  const maxBodyBytes = cfg.maxBodyBytes ?? 32 * 1024 * 1024;
  const env = cfg.env ?? minimalEnv();
  const stats: HookBridgeStats = { calls: 0, pings: 0, refused: 0, failed: 0 };
  const children = new Set<ReturnType<typeof spawn>>();

  const handle = (req: IncomingMessage, res: ServerResponse) => {
    const m = /^\/hook\/([^/]+)\/([^/]+)\/(ping|\d{1,4})$/.exec(req.url ?? '');
    const refuse = (status: number, why: string) => {
      stats.refused++;
      req.resume();
      reply(res, status, 2, '', `papercusp hook bridge: ${why}\n`);
    };
    if (req.method !== 'POST' || !m) return refuse(404, 'unknown request');
    const [, session, token, which] = m as unknown as [string, string, string, string];
    if (!HOOK_SESSION_NAME.test(session)) return refuse(404, 'unknown session');
    const rec = readHookRecord(recordDir, session);
    if (!rec || !tokenMatches(rec.token, token)) return refuse(403, 'unknown session or token');
    if (which === 'ping') {
      stats.pings++;
      req.resume();
      return reply(res, 200, 0, '', '');
    }
    const cmd = rec.commands[Number(which)];
    if (!cmd) return refuse(404, `no hook #${which}`);

    const chunks: Buffer[] = [];
    let size = 0;
    let tooBig = false;
    req.on('data', (c: Buffer) => {
      size += c.length;
      if (size > maxBodyBytes) tooBig = true;
      else chunks.push(c);
    });
    req.on('error', () => undefined);
    req.on('end', () => {
      if (tooBig) return refuse(413, `payload over ${maxBodyBytes} bytes`);
      stats.calls++;
      // `setsid` makes the hook its own process group (it execs in place: a non-leader child needs no fork), so a
      // timeout kills the whole hook tree. Killing only `sh` would leave a grandchild holding the output pipes open.
      const child = spawn('setsid', ['/bin/sh', '-c', cmd.command], { env, cwd: tmpdir(), stdio: ['pipe', 'pipe', 'pipe'] });
      children.add(child);
      const out: Buffer[] = [];
      const err: Buffer[] = [];
      child.stdout!.on('data', (c: Buffer) => out.push(c));
      child.stderr!.on('data', (c: Buffer) => err.push(c));
      child.stdin!.on('error', () => undefined);
      child.stdin!.end(Buffer.concat(chunks));
      const timeoutSec = cmd.timeoutSec && cmd.timeoutSec > 0 ? cmd.timeoutSec : defaultTimeoutSec;
      let timedOut = false;
      const timer = setTimeout(() => {
        timedOut = true;
        killTree(child);
      }, timeoutSec * 1000);
      child.on('error', (e) => {
        clearTimeout(timer);
        children.delete(child);
        stats.failed++;
        reply(res, 200, 127, '', `papercusp hook bridge: cannot run hook: ${e.message}\n`);
      });
      child.on('close', (code, signal) => {
        clearTimeout(timer);
        if (!children.delete(child)) return; // 'error' already replied
        const exit = timedOut ? 124 : code ?? (signal ? 128 : 1);
        if (exit !== 0) stats.failed++;
        const stderr = Buffer.concat(err);
        reply(res, 200, exit, Buffer.concat(out), timedOut ? Buffer.concat([stderr, Buffer.from(`papercusp hook bridge: hook timed out after ${timeoutSec}s\n`)]) : stderr);
      });
    });
  };

  const server = createServer(handle);
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => resolve());
  });
  const port = (server.address() as { port: number }).port;
  let stopped = false;
  return {
    port,
    recordDir,
    stats: () => ({ ...stats }),
    async stop() {
      if (stopped) return;
      stopped = true;
      for (const c of children) killTree(c);
      server.closeAllConnections?.();
      await new Promise<void>((r) => server.close(() => r()));
    },
  };
}

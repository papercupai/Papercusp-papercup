/**
 * Guard for WI-4978 (Papercusp org vs papercupai login identity confusion).
 *
 * The canonical product repositories live under the `Papercusp` GitHub
 * Organization; `papercupai` is a GitHub User (the maintainer's personal
 * admin login) and does not own product repos. At least one owner-facing
 * link (`apps/operator/app/support/page.tsx`'s "Open a GitHub issue" button)
 * hardcoded `github.com/papercupai/papercusp` — a repo that has never
 * existed under that owner, so the link 404s. See
 * `canonical-github-identity.ts` for the single source of truth these links
 * should be built from.
 *
 * This test fails the build the moment a NEW hardcoded
 * `github.com/papercupai/<papercup-or-papercusp>` link is committed anywhere
 * in the tree, tracked file or fresh-but-untracked (a brand new file is
 * exactly where a fresh identity mix-up is most likely to land — see
 * `listFilesIncludingUntracked`'s own rationale).
 *
 * Deliberately narrow: `papercupai/<anything-else>` is NOT flagged, because
 * several tests (e.g. `operator-public/src/__tests__/listings.test.ts`) use
 * `papercupai` as a generic example GitHub username in fixture data — that
 * is unrelated to this product's own identity and would be a false positive.
 * What's unambiguous, and the actual bug class observed live, is `papercupai`
 * paired with THIS product's own repo name.
 *
 * One further nuance: `papercupai/papercup` (unlike `papercupai/papercusp`,
 * a repo name that has never existed under ANY owner) is not intrinsically
 * impossible — GitHub lets any user fork any repo under their own login, so
 * a *personal fork* legitimately lives at `papercupai/papercup`. A handful of
 * fork-PR unit tests use exactly that shape as generic fixture data for a
 * parameterized fork/PR flow (the function under test takes owner/repo as
 * plain arguments — nothing about the assertion depends on which identity is
 * "canonical"). Those are allowlisted below rather than treated as drift.
 */
import { afterEach, describe, expect, it } from 'vitest';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
// eslint-disable-next-line import/no-relative-packages
import { listFilesIncludingUntracked } from '../../../scripts/lib/tracked-files.mjs';

const ROOT = join(__dirname, '../../..');

/** Matches the exact wrong pattern: papercupai treated as the owner of the product repo. */
const WRONG_OWNER_REPO = /github\.com\/papercupai\/(papercup|papercusp)\b/i;

/**
 * Generated build-output mirrors (Starlight `dist`/preview + the operator's
 * committed public/docs and public/internal/docs static mirrors) reflect
 * whatever the source docs said at last build time — they are regenerated by
 * `npm run build`, never hand-edited, and are therefore not a source of
 * truth to guard here. Guard the SOURCE files that actually produce them.
 */
const EXCLUDED_PATH_SEGMENTS = [
  '/dist/',
  '/dist-preview/',
  'apps/operator/public/docs/',
  'apps/operator/public/internal/docs/',
  // bundled/vendored sidecar JS (build output, not hand-edited source)
  'papercusp-desktop/src-tauri/env-sidecars/',
  // these files' own explanatory comments quote the wrong pattern as an example
  'packages/operator-core/lib/github-identity-drift.test.ts',
  'packages/operator-core/lib/canonical-github-identity.ts',
];

/**
 * Generic `papercupai/papercup` fork/PR fixtures (see the file-header note
 * above) — the function under test in each is parameterized over owner/repo,
 * so the fixture's identity choice carries no product-identity assertion.
 * Exact-path allowlist, not a pattern, so a NEW file elsewhere still trips
 * the guard.
 */
const ALLOWLISTED_FORK_FIXTURES = new Set([
  'packages/operator-core/lib/harness/open-fork-pr.test.ts',
  'packages/operator-core/lib/harness/fork-pr-contrib.test.ts',
  'packages/operator-core/lib/harness/fork-pr-on-feature-pass.test.ts',
  'packages/operator-core/lib/harness/feature-pr-producer.test.ts',
  'packages/operator-core/lib/harness-insights/__tests__/load-all.test.ts',
  'apps/operator/app/harness/insights/__tests__/ProjectCard.test.tsx',
]);

const TEXT_EXTENSIONS = /\.(ts|tsx|js|jsx|mjs|cjs|mdx|md|astro|json|html)$/i;

function findIdentityDrift(root: string, files = (listFilesIncludingUntracked(root) as { files: string[] }).files) {
  const offenders: Array<{ path: string; line: number; text: string }> = [];

  for (const relPath of files) {
    if (!TEXT_EXTENSIONS.test(relPath)) continue;
    if (EXCLUDED_PATH_SEGMENTS.some((seg) => relPath.includes(seg))) continue;
    if (ALLOWLISTED_FORK_FIXTURES.has(relPath)) continue;
    // Managed report snapshots archive historical plan/work-item text, including
    // deliberately quoted bad-link examples. They are generated evidence, not
    // authored product links. Keep ordinary docs/evidence JSON in the scan.
    if (relPath.startsWith('.papercusp/reports/')) continue;

    let content: string;
    try {
      content = readFileSync(join(root, relPath), 'utf8');
    } catch {
      continue; // symlink / race / binary — not this guard's concern
    }
    if (!WRONG_OWNER_REPO.test(content)) continue;

    content.split('\n').forEach((line, idx) => {
      const match = WRONG_OWNER_REPO.exec(line);
      if (!match) return;
      // A one-line JSON source can be megabytes long. Show the offending link
      // with bounded surrounding context rather than dumping the entire file.
      const start = Math.max(0, match.index - 80);
      const end = Math.min(line.length, match.index + match[0].length + 80);
      const text = line.length <= 320 ? line.trim()
        : `${start > 0 ? '… ' : ''}${line.slice(start, end)}${end < line.length ? ' …' : ''}`;
      offenders.push({ path: relPath, line: idx + 1, text });
    });
  }
  return offenders;
}

describe('github identity drift guard (WI-4978)', () => {
  const fixtureRoots: string[] = [];
  afterEach(() => {
    for (const root of fixtureRoots.splice(0)) rmSync(root, { recursive: true, force: true });
  });
  const fixture = () => {
    const root = mkdtempSync(join(tmpdir(), 'github-identity-source-'));
    fixtureRoots.push(root);
    return root;
  };
  const write = (root: string, path: string, content: string) => {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  };

  it('ignores generated historical reports while detecting fresh authored TS and evidence JSON', () => {
    const root = fixture();
    const link = 'https://github.com/papercupai/papercup';
    const report = '.papercusp/reports/portfolio/snapshot.json';
    write(root, report, JSON.stringify({ plans: [{ content: link }] }));
    // Supply the Git-enumerated path shape: a non-Git filesystem fallback
    // skips .papercusp before the source/artifact boundary can be exercised.
    expect(findIdentityDrift(root, [report])).toEqual([]);
    write(root, 'apps/operator/app/support/page.tsx', `export const issueUrl = '${link}';`);
    write(root, 'docs/evidence/source.json', JSON.stringify({ issueUrl: link }));
    expect(findIdentityDrift(root, [report, 'apps/operator/app/support/page.tsx', 'docs/evidence/source.json'])
      .map(row => row.path).sort()).toEqual([
      'apps/operator/app/support/page.tsx', 'docs/evidence/source.json',
    ]);
  });

  it('keeps similarly named authored paths in scope', () => {
    const root = fixture();
    write(root, '.papercusp/reports-source/navigation.json', '{"url":"https://github.com/papercupai/papercusp"}');
    expect(findIdentityDrift(root, ['.papercusp/reports-source/navigation.json'])).toEqual([
      expect.objectContaining({ path: '.papercusp/reports-source/navigation.json', line: 1 }),
    ]);
  });

  it('bounds a long source-line diagnostic around the actual offending link', () => {
    const root = fixture();
    const link = 'https://github.com/papercupai/papercup';
    write(root, 'docs/navigation.json', JSON.stringify({ padding: 'x'.repeat(100_000), issueUrl: link }));
    const offenders = findIdentityDrift(root);
    expect(offenders).toHaveLength(1);
    expect(offenders[0]).toMatchObject({ path: 'docs/navigation.json', line: 1 });
    expect(offenders[0]!.text).toContain(link);
    expect(offenders[0]!.text.length).toBeLessThan(320);
  });

  it('no source file links to papercupai as if it owned the product repo', () => {
    const offenders = findIdentityDrift(ROOT);

    if (offenders.length > 0) {
      const detail = offenders
        .map((o) => `  ${o.path}:${o.line}: ${o.text}`)
        .join('\n');
      throw new Error(
        `Found ${offenders.length} link(s) pointing to papercupai as if it owned the product repo ` +
          `(the canonical org is 'Papercusp', repo 'papercup' — see canonical-github-identity.ts):\n${detail}`,
      );
    }

    expect(offenders).toEqual([]);
  });

  it('the canonical constants resolve to the real remote (Papercusp/papercup)', async () => {
    const {
      GITHUB_ORG,
      GITHUB_REPO,
      GITHUB_REPO_SLUG,
      GITHUB_REPO_URL,
      GITHUB_ISSUES_URL,
      GITHUB_NEW_ISSUE_URL,
      GITHUB_MAINTAINER_LOGIN,
    } = await import('./canonical-github-identity');

    expect(GITHUB_ORG).toBe('Papercusp');
    expect(GITHUB_REPO).toBe('papercup');
    expect(GITHUB_REPO_SLUG).toBe('Papercusp/papercup');
    expect(GITHUB_REPO_URL).toBe('https://github.com/Papercusp/papercup');
    expect(GITHUB_ISSUES_URL).toBe('https://github.com/Papercusp/papercup/issues');
    expect(GITHUB_NEW_ISSUE_URL).toBe('https://github.com/Papercusp/papercup/issues/new');
    // The maintainer's personal login is a distinct, deliberately-not-org identity.
    expect(GITHUB_MAINTAINER_LOGIN).toBe('papercupai');
    expect(GITHUB_MAINTAINER_LOGIN).not.toBe(GITHUB_ORG);
  });
});

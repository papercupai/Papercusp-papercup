import { promises as fs } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { assertPinnedGcpSecretReference, createSecretRefResolver, parseGcpSecretReference, resolveSecretRef } from './secret-ref';

const auth = vi.hoisted(() => ({ metadata: vi.fn(), adc: vi.fn() }));
vi.mock('google-auth-library', () => ({
  Compute: class { getAccessToken = auth.metadata; },
  GoogleAuth: class { getAccessToken = auth.adc; },
}));

const RESOURCE = 'projects/123456789012/locations/us-central1/secrets/stripe-key/versions/3';
const SECRET_REF_PREFIX = ['gcp', 'secret'].join('-') + ':';
const REFERENCE = `${SECRET_REF_PREFIX}${RESOURCE}`;
// Independent CRC32C check vector, not a checksum generated by the implementation under test.
const PAYLOAD = { name: RESOURCE, payload: { data: 'MTIzNDU2Nzg5', dataCrc32c: '3808858755' } };

afterEach(() => {
  delete process.env.EGRESS_TEST_SECRET;
  vi.resetAllMocks();
});

describe('Secret Manager references', () => {
  it('uses the regional endpoint, verifies the resource/checksum and returns only the value', async () => {
    const fetchImpl = vi.fn<typeof fetch>(async () => Response.json(PAYLOAD));
    const resolver = createSecretRefResolver({ fetch: fetchImpl, accessToken: async () => 'test-token' });
    await expect(resolver(` ${REFERENCE} `)).resolves.toBe('123456789');
    expect(fetchImpl).toHaveBeenCalledWith(
      `https://secretmanager.us-central1.rep.googleapis.com/v1/${RESOURCE}:access`,
      expect.objectContaining({ headers: { authorization: 'Bearer test-token' }, redirect: 'error', signal: expect.any(AbortSignal) }),
    );
  });

  it('uses the VM metadata identity in production and ADC only for development', async () => {
    auth.metadata.mockResolvedValue({ token: 'metadata-token' });
    auth.adc.mockResolvedValue('adc-token');
    const fetchImpl = vi.fn<typeof fetch>(async () => Response.json(PAYLOAD));
    await createSecretRefResolver({ env: { PAPERCUSP_DEPLOYMENT_ENVIRONMENT: 'production' }, fetch: fetchImpl })(REFERENCE);
    expect(auth.metadata).toHaveBeenCalledOnce();
    expect(auth.adc).not.toHaveBeenCalled();
    await createSecretRefResolver({ env: {}, fetch: fetchImpl })(REFERENCE);
    expect(auth.adc).toHaveBeenCalledOnce();
    expect(fetchImpl.mock.calls.map(([, init]) => init?.headers)).toEqual([
      { authorization: 'Bearer metadata-token' }, { authorization: 'Bearer adc-token' },
    ]);
  });

  it.each([
    `${SECRET_REF_PREFIX}https://attacker.example/secret`,
    `${SECRET_REF_PREFIX}projects/cloud-prod-test/locations/us-central1/secrets/key/versions/1`,
    `${SECRET_REF_PREFIX}projects/123456789012/locations/us-central1/../secrets/key/versions/1`,
    `${SECRET_REF_PREFIX}projects/123456789012/secrets/key/versions/0`,
    `${REFERENCE}?redirect=attacker`,
  ])('rejects malformed resource %s before acquiring credentials', async (reference) => {
    const accessToken = vi.fn(async () => 'must-not-read');
    await expect(createSecretRefResolver({ accessToken })(reference)).rejects.toThrow('gcp_secret_ref_malformed');
    expect(accessToken).not.toHaveBeenCalled();
  });

  it.each([
    { ...PAYLOAD, name: RESOURCE.replace('stripe-key', 'another-tenant') },
    { ...PAYLOAD, payload: { ...PAYLOAD.payload, dataCrc32c: '0' } },
    { ...PAYLOAD, payload: { data: 'credential-sentinel', dataCrc32c: '0' } },
    { ...PAYLOAD, payload: { data: '', dataCrc32c: '0' } },
    { ...PAYLOAD, payload: { data: 'MTIzNDU2Nzg5' } },
  ])('fails closed on a wrong resource, damaged or empty payload without leaking provider content', async (payload) => {
    const resolve = createSecretRefResolver({ accessToken: async () => 'test-token', fetch: async () => Response.json(payload) });
    await expect(resolve(REFERENCE)).rejects.toThrow(/^gcp_secret_ref_resolution_failed$/);
  });

  it('does not leak IAM denial text, token failures or provider errors', async () => {
    const fetchImpl = vi.fn<typeof fetch>(async () => new Response('credential-sentinel', { status: 403 }));
    await expect(createSecretRefResolver({ accessToken: async () => 'test-token', fetch: fetchImpl })(REFERENCE))
      .rejects.toThrow(/^gcp_secret_ref_resolution_failed$/);
    fetchImpl.mockClear();
    await expect(createSecretRefResolver({ accessToken: async () => { throw new Error('credential-sentinel'); }, fetch: fetchImpl })(REFERENCE))
      .rejects.toThrow(/^gcp_secret_ref_resolution_failed$/);
    expect(fetchImpl).not.toHaveBeenCalled();
  });

  it('accepts a global resource but requires a pinned version for production references', () => {
    expect(parseGcpSecretReference(`${SECRET_REF_PREFIX}projects/123456/secrets/key/versions/1`)?.endpoint)
      .toBe('https://secretmanager.googleapis.com');
    expect(() => assertPinnedGcpSecretReference(REFERENCE)).not.toThrow();
    for (const reference of ['env:KEY', 'file:/run/secret', 'integration:KEY', REFERENCE.replace('/3', '/latest')]) {
      expect(() => assertPinnedGcpSecretReference(reference)).toThrow('requires_pinned_secret_manager');
    }
  });
});

describe('resolveSecretRef', () => {
  it('resolves env:NAME from process.env', async () => {
    process.env.EGRESS_TEST_SECRET = 'shh';
    await expect(resolveSecretRef('env:EGRESS_TEST_SECRET')).resolves.toBe('shh');
  });

  it('throws when the env var is unset', async () => {
    await expect(resolveSecretRef('env:EGRESS_TEST_SECRET')).rejects.toThrow(/not set/);
  });

  it('resolves file:<path> to the trimmed file contents', async () => {
    const path = join(tmpdir(), `egress-secret-${Date.now()}.txt`);
    await fs.writeFile(path, '  key-value-123  \n');
    try {
      await expect(resolveSecretRef(`file:${path}`)).resolves.toBe('key-value-123');
    } finally {
      await fs.unlink(path);
    }
  });

  it('throws for an unsupported ref shape', async () => {
    await expect(resolveSecretRef('ftp:whatever')).rejects.toThrow(/unsupported secret ref/);
  });

  it('throws for an empty secret file', async () => {
    const path = join(tmpdir(), `egress-secret-empty-${Date.now()}.txt`);
    await fs.writeFile(path, '   \n');
    try {
      await expect(resolveSecretRef(`file:${path}`)).rejects.toThrow(/empty/);
    } finally {
      await fs.unlink(path);
    }
  });
});

/**
 * dependency-endpoint-gate.integration.test.ts — the endpoint detector's verdict, run over the
 * output of every REAL WRITER, as a build-time gate.
 *
 * Plan: dependency-subsystem-thorough-testing-2026-08-02 (P-013).
 * @covers INV-01 INV-02 INV-12 INV-13
 *
 * WHY THIS EXISTS WHEN THE DETECTOR IS ALREADY WELL-TESTED. work-item-deps-integrity.
 * integration.test.ts has 13 cases and is a good suite — but every row in it is a hand-written
 * INSERT, including its "reports ZERO defects for correctly-written edges" baseline. That
 * baseline hand-writes what the author believed the correct form to be and asserts the detector
 * accepts it. So it proves the detector is silent on clean input; it cannot prove that the
 * system PRODUCES clean input, because no writer ever runs in it.
 *
 * That is the tautology shape this plan keeps finding (P-002's header calls it out for the
 * fixture factory): a test that generates a row from its own understanding of a convention and
 * then asserts a checker agrees is really a test that one belief matches another belief. It
 * stays green with every production writer deleted.
 *
 * So the gate here inverts the direction. Nothing hand-writes an endpoint: every edge is made
 * by a real production writer, and the REAL detector — the same `reconcileWorkItemDepEndpoints`
 * the hourly readiness-drift-monitor calls — is asked for its verdict. A writer that bypasses
 * the ref-form seam fails THIS BUILD, rather than surfacing up to an hour later as a log line
 * nobody reads, detached from the change that caused it.
 *
 * DETECT-ONLY IS THE POLICY (plan P-013, per D-010/D-014). This gate reports and fails; it
 * never repairs. Auto-repair would make the detector a second edge writer, which is the exact
 * thing the enumerated-writer census exists to prevent.
 *
 * ⚠ THE GATE CARRIES ITS OWN NEGATIVE CONTROL. Every assertion here is `defects === 0`, which
 * is also what a detector that can never fire produces, and what a fixture that wrote no edges
 * at all produces. Two controls therefore run alongside: one proves the detector still FIRES on
 * a known-bad endpoint in this exact fixture, and one proves the writers actually wrote
 * something. Without both, this file would be INV-12's own failure mode wearing a gate's
 * costume.
 *
 * Real Postgres (testcontainer; Docker required).
 *
 * Run:
 *   cd packages/operator-core && npx vitest run --config vitest.integration.config.ts \
 *     lib/scheduler/dependency-endpoint-gate.integration.test.ts
 */

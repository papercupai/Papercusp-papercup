describe('the endpoint detector returns a CLEAN verdict over every real writer', () => {
  // @covers INV-01 INV-02
  it('PROMOTION (plan-workitem-promotion-run.ts) writes endpoints the detector accepts', async () => {
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Prereq' },
      { id: 'P-002', text: 'Dependent', blockedBy: ['P-001'] },
    ]);
    expect(ids.size).toBe(2);

    // The writers actually wrote — otherwise `defects: 0` is the verdict on an empty table.
    expect(await endpointRowCount()).toBeGreaterThan(0);
    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });

  // @covers INV-01 INV-02
  it('the LINK door (work-items.ts) writes endpoints the detector accepts — FEATURE family', async () => {
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Prereq' },
      { id: 'P-002', text: 'Dependent' },
    ]);
    const blocker = ids.get('Prereq')!;
    const blocked = ids.get('Dependent')!;

    const res = await wi.linkWorkItem(blocker, { kind: FEATURE_KIND, ref: featureRef(H, blocked) }, 'blocks', {
      harness: H,
      by: 'su-test',
    });
    expect(res).toEqual({ ok: true });

    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });

  // @covers INV-01 INV-02
  it('the LINK door writes endpoints the detector accepts — ISSUE family (the D-017 shape)', async () => {
    // The family whose ref convention D-017 got wrong, through the door where it was wrong.
    // The feature leg was always correct, so covering only that would repeat the mistake.
    await seedIssue('WI-9001');
    await seedIssue('WI-9002');

    await wi.linkWorkItem('WI-9001', { kind: ISSUE_KIND, ref: 'WI-9002' }, 'blocks', { harness: H, by: 'su-test' });

    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });

  // @covers INV-01 INV-02
  it('syncFeatureBlockEdges (dbos/feature-blockers-edges.ts) writes endpoints the detector accepts', async () => {
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Prereq' },
      { id: 'P-002', text: 'Dependent' },
    ]);
    await syncFeatureBlockEdges(H, ids.get('Dependent')!, [ids.get('Prereq')!]);

    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });

  // @covers INV-01 INV-02
  it('the UNLINK door leaves no orphaned endpoint behind', async () => {
    // Removal is a writer too. A remove that deletes one side of a mirrored pair leaves a
    // dangling endpoint — clean by every count-based check, and exactly what the detector's
    // `dangling` bucket exists to catch.
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Prereq' },
      { id: 'P-002', text: 'Dependent' },
    ]);
    const blocker = ids.get('Prereq')!;
    const dst = { kind: FEATURE_KIND, ref: featureRef(H, ids.get('Dependent')!) };

    await wi.linkWorkItem(blocker, dst, 'blocks', { harness: H, by: 'su-test' });
    expect(await verdict()).toMatchObject({ defects: 0 });

    // NB: unlinkWorkItem's opts are { harness? } only — it takes no `by`, unlike its link
    // counterpart. An excess property here is runtime-harmless, so vitest passes it happily;
    // only the typecheck catches it.
    await wi.unlinkWorkItem(blocker, dst, 'blocks', { harness: H });
    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });

  // @covers INV-01 INV-02
  it('ALL writers together, in one graph, still produce a clean verdict', async () => {
    // Each case above exercises one writer in isolation. Real state is written by several,
    // and a defect can be a product of two writers disagreeing about a convention rather than
    // either one being wrong alone — which per-writer cases structurally cannot surface.
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Alpha' },
      { id: 'P-002', text: 'Beta', blockedBy: ['P-001'] },
      { id: 'P-003', text: 'Gamma' },
    ]);
    await seedIssue('WI-8001');
    await seedIssue('WI-8002');

    await syncFeatureBlockEdges(H, ids.get('Gamma')!, [ids.get('Alpha')!]);
    await wi.linkWorkItem(ids.get('Alpha')!, { kind: FEATURE_KIND, ref: featureRef(H, ids.get('Beta')!) }, 'blocks', {
      harness: H,
      by: 'su-test',
    });
    await wi.linkWorkItem('WI-8001', { kind: ISSUE_KIND, ref: 'WI-8002' }, 'blocks', { harness: H, by: 'su-test' });

    expect(await endpointRowCount()).toBeGreaterThan(2);
    expect(await verdict()).toMatchObject({ defects: 0, mismatched: [], dangling: [] });
  });
});


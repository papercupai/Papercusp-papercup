// @covers INV-12
describe('the gate can actually fail', () => {
  it('FIRES on a mis-declared endpoint written into this very fixture', async () => {
    // Without this, every `defects: 0` above is equally explained by a detector wired to
    // nothing, a schema the detector cannot read, or a mock that silently returns empty. Here
    // the one hand-written row in the file is deliberately wrong, in the exact live D-017
    // shape: an ISSUE-family item declared 'feature' and written harness-qualified.
    await seedIssue('WI-7001');
    await seedIssue('WI-7002');
    await db.sql`
      INSERT INTO harness_shared.work_item_deps
        (workspace_id, blocked_kind, blocked_ref, blocker_kind, blocker_ref, dep_type)
      VALUES (${WS}, 'feature', ${`${H}#WI-7002`}, 'issue', 'WI-7001', 'blocks')`;

    const res = await verdict();
    expect(res.defects).toBeGreaterThan(0);
    expect(res.mismatched.length).toBeGreaterThan(0);
  });

  it('FIRES on an endpoint that resolves to nothing', async () => {
    // The other defect bucket, which is repaired differently (delete vs re-point) and so must
    // be shown to be detected separately rather than folded into the count above.
    await seedIssue('WI-7003');
    await db.sql`
      INSERT INTO harness_shared.work_item_deps
        (workspace_id, blocked_kind, blocked_ref, blocker_kind, blocker_ref, dep_type)
      VALUES (${WS}, 'issue', 'WI-7003', 'issue', 'WI-DOES-NOT-EXIST', 'blocks')`;

    const res = await verdict();
    expect(res.defects).toBeGreaterThan(0);
    expect(res.dangling.length).toBeGreaterThan(0);
  });
});


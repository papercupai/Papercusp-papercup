describe('syncFeatureBlockEdges writes EFFECTIVE edges, and REPLACES on every call', () => {
  it('gates the blocked item, then releases it when the blocker is terminal', async () => {
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'Prereq' },
      { id: 'P-002', text: 'Dependent' },
    ]);
    const blocker = ids.get('Prereq')!;
    const blocked = ids.get('Dependent')!;
    await setFeatureStatus(blocker, 'wip');
    await setFeatureStatus(blocked, 'open');

    expect(await claim()).toBe(blocked); // positive control
    await db.sql`UPDATE harness_shared.harness_features_consolidated SET taken_by=NULL, status='open' WHERE feature_id=${blocked}`;

    await syncFeatureBlockEdges(H, blocked, [blocker]);

    expect(await claim()).toBeNull();
    await setFeatureStatus(blocker, 'passed');
    expect(await claim()).toBe(blocked);
  });

  it('REPLACE semantics, stated as behaviour: a second call drops the first call’s gate', async () => {
    // This is the fact that makes INV-10 necessary rather than pedantic, so it is asserted
    // here as an observable claim outcome instead of being described in a comment. At
    // promotion the semantics is correct (the item was minted microseconds earlier and has no
    // edges to lose); anywhere else it is a silent deletion.
    const ids = await promoteFeatures([
      { id: 'P-001', text: 'First blocker' },
      { id: 'P-002', text: 'Second blocker' },
      { id: 'P-003', text: 'Dependent' },
    ]);
    const first = ids.get('First blocker')!;
    const second = ids.get('Second blocker')!;
    const blocked = ids.get('Dependent')!;
    for (const id of [first, second]) await setFeatureStatus(id, 'wip');
    await setFeatureStatus(blocked, 'open');

    await syncFeatureBlockEdges(H, blocked, [first]);
    expect(await claim()).toBeNull();

    // Re-sync naming only the SECOND blocker. If this UNIONed, the first would still gate.
    await syncFeatureBlockEdges(H, blocked, [second]);
    expect((await edges()).map((e) => e.blocker_ref)).toEqual([featureRef(H, second)]);

    // The proof it is a real deletion and not just a missing row: satisfy ONLY the second
    // blocker and the item is served, while the first is still non-terminal.
    await setFeatureStatus(second, 'passed');
    expect(await claim()).toBe(blocked);
  });
});


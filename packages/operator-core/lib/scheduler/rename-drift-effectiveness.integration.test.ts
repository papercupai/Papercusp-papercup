describe('a blocking edge survives a pot re-home — proven at the claim door', () => {
  // @covers INV-03 INV-04
  it('still WITHHOLDS the dependent after the pot is renamed', async () => {
    const { blocker, blocked } = await seedGatedPair();

    // Gate closed at the OLD slug. (The pairing positive control is the next test; here the
    // pre-condition is what makes the post-rename null meaningful.)
    expect(await claim(OLD_H)).toBeNull();
    expect(await edges()).toEqual([
      { blocked_ref: featureRef(OLD_H, blocked), blocker_ref: featureRef(OLD_H, blocker) },
    ]);

    // THE RE-HOME — both items move, as a whole-pot rename does.
    await reHome(blocker, OLD_H, NEW_H);
    await reHome(blocked, OLD_H, NEW_H);

    // The refs moved with them. Reported, not the verdict.
    expect(await edges()).toEqual([
      { blocked_ref: featureRef(NEW_H, blocked), blocker_ref: featureRef(NEW_H, blocker) },
    ]);

    // THE VERDICT: the dependency is still enforced at the NEW slug. This is the assertion the
    // incident would have failed — there the edge kept naming the old slug and gated nothing.
    expect(await claim(NEW_H)).toBeNull();
  });

  // @covers INV-05
  it('and RELEASES the dependent once the blocker goes terminal — so the null was the edge', async () => {
    // Without this, every null above is equally explained by "the fixture never made the item
    // claimable in the first place". This shows the very same item being SERVED at the new slug
    // the moment the edge is satisfied, which is only possible if it was the edge withholding it.
    const { blocker, blocked } = await seedGatedPair();
    await reHome(blocker, OLD_H, NEW_H);
    await reHome(blocked, OLD_H, NEW_H);

    expect(await claim(NEW_H)).toBeNull();

    await setFeatureStatus(blocker, 'passed');

    expect(await claim(NEW_H)).toBe(blocked);
  });

  // @covers INV-03
  it('the guard has TEETH: without the 734 trigger the same re-home makes the item claimable', async () => {
    // The negative control. Every other assertion in this file is "the item stayed blocked",
    // which an inert fixture also produces. This one proves the harness can actually observe the
    // regression: drop the seam, and the exact same steps reproduce the live incident.
    await db.sql.unsafe(`DROP TRIGGER IF EXISTS repoint_qualified_refs_trg ON harness_shared.work_items`);
    try {
      const { blocker, blocked } = await seedGatedPair();
      expect(await claim(OLD_H)).toBeNull(); // gate closed before the re-home

      await reHome(blocker, OLD_H, NEW_H);
      await reHome(blocked, OLD_H, NEW_H);

      // The edge is untouched — still naming the OLD slug, still form-valid, still mirrored,
      // still acyclic. Every row-shape check passes. And it now gates nothing.
      expect(await edges()).toEqual([
        { blocked_ref: featureRef(OLD_H, blocked), blocker_ref: featureRef(OLD_H, blocker) },
      ]);
      expect(await claim(NEW_H)).toBe(blocked); // ← the incident, reproduced
    } finally {
      await applyMigrationForTest(db.sql, MIGRATION_734);
    }
  });
});

describe('partial re-homes — only one endpoint moves', () => {
  // @covers INV-03 INV-04
  it('BLOCKED side alone: the dependent moves, the blocker stays, the gate holds', async () => {
    // A single item re-homed between pots (not a whole-pot rename) rewrites only one side of the
    // edge. The trigger fires per-row, so this is the case where a naive whole-pot repair — one
    // that assumed both endpoints move together — would silently drop the gate.
    const { blocker, blocked } = await seedGatedPair();

    await reHome(blocked, OLD_H, NEW_H);

    expect(await edges()).toEqual([
      { blocked_ref: featureRef(NEW_H, blocked), blocker_ref: featureRef(OLD_H, blocker) },
    ]);
    expect(await claim(NEW_H)).toBeNull();

    await setFeatureStatus(blocker, 'passed');
    expect(await claim(NEW_H)).toBe(blocked); // still the edge, not a fixture artifact
  });

  // @covers INV-03 INV-04
  it('BLOCKER side alone: the blocker moves out, the dependent stays gated where it is', async () => {
    // The mirror case, and the one with a cross-pot dependency in it: after this the blocker
    // lives in a different pot from the item it blocks, which is the normal steady state once a
    // pot splits. The blocker_ref must follow it or the gate evaporates.
    const { blocker, blocked } = await seedGatedPair();

    await reHome(blocker, OLD_H, NEW_H);

    expect(await edges()).toEqual([
      { blocked_ref: featureRef(OLD_H, blocked), blocker_ref: featureRef(NEW_H, blocker) },
    ]);
    expect(await claim(OLD_H)).toBeNull();

    await setFeatureStatus(blocker, 'passed');
    expect(await claim(OLD_H)).toBe(blocked);
  });
});

describe('the maintained-readiness sidecar tracks the re-home', () => {
  // @covers INV-03 INV-04
  it('work_item_blocked ends up keyed to the NEW slug, so the anti-join still finds the item', async () => {
    // `work_item_blocked` is keyed (workspace, harness_slug, feature_id) and migration 734 does
    // not touch it — the re-home is caught only because the repoint's own UPDATE on
    // work_item_deps fires wir_deps_sync_trg, which re-syncs at the new key. That cascade is
    // load-bearing and entirely undocumented: with SCHEDULER_MAINTAINED_READY ON the claim door
    // reads THIS table, so a sidecar left at the old key means the dependent is served while
    // its edge is perfectly correct. Pinning it here so a future change to 734's write path
    // (or a DISABLE TRIGGER around it) cannot quietly break readiness.
    const { blocked } = await seedGatedPair();

    expect(await blockedSidecar()).toEqual([{ harness_slug: OLD_H, feature_id: blocked }]);

    await reHome(blocked, OLD_H, NEW_H);

    const rows = await blockedSidecar();
    expect(rows).toContainEqual({ harness_slug: NEW_H, feature_id: blocked });
    // …and the claim door agrees with the sidecar, which is the property that actually matters.
    expect(await claim(NEW_H)).toBeNull();
  });

  // @covers INV-03 INV-04
  it('and it is wir_deps_sync_trg doing it — drop that trigger and the re-home strands readiness', async () => {
    // The test above proves the OUTCOME (the sidecar lands at the new key). This one proves the
    // MECHANISM, because the two are worth separating: the outcome is what we need, and the
    // mechanism is an accident we are relying on. Migration 734 never writes work_item_blocked.
    // The sidecar is only corrected because 734's UPDATE of work_item_deps happens to fire
    // wir_deps_sync_trg, which re-syncs at the ref's new key.
    //
    // Removing that one trigger — while 734 itself is fully intact and every ref is repointed
    // perfectly — should therefore serve a blocked item. If it does, readiness across a rename
    // is load-bearing on an undocumented cascade, and migration 734's own DISABLE-TRIGGER
    // warning names only `repoint_qualified_refs_trg`, which is not sufficient.
    const { blocker, blocked } = await seedGatedPair();
    expect(await blockedSidecar()).toEqual([{ harness_slug: OLD_H, feature_id: blocked }]);

    await db.sql.unsafe(`DROP TRIGGER IF EXISTS wir_deps_sync_trg ON harness_shared.work_item_deps`);
    try {
      await reHome(blocker, OLD_H, NEW_H);
      await reHome(blocked, OLD_H, NEW_H);

      // 734 did its job perfectly — the refs are correct.
      expect(await edges()).toEqual([
        { blocked_ref: featureRef(NEW_H, blocked), blocker_ref: featureRef(NEW_H, blocker) },
      ]);
      // …and readiness is stranded at the OLD key, which no claim for the new slug can find.
      expect(await blockedSidecar()).toEqual([{ harness_slug: OLD_H, feature_id: blocked }]);
      expect(await claim(NEW_H)).toBe(blocked); // ← correct refs, blocked item, served anyway
    } finally {
      await db.sql.unsafe(WORK_ITEM_DEPS_DDL).simple();
    }
  });
});

describe('the issue family is unaffected — and that is a property, not an omission', () => {
  // @covers INV-03
  it('BARE issue refs are left alone by a re-home and keep gating', async () => {
    // Only feature-family endpoints are harness-qualified (D-009 rule 1); the issue floor matches
    // on the BARE id. So a re-home must NOT rewrite an issue ref — doing so would break the issue
    // floor exactly as leaving a feature ref stale breaks the feature one. The two families fail
    // in opposite directions, which is why this case is asserted rather than assumed.
    await db.sql`
      INSERT INTO harness_shared.work_items
        (harness_slug, feature_id, title, status, item_kind, workspace_id, taken_by, created_ts, updated_ts, payload)
      VALUES (${OLD_H}, 'WI-B1', 'blocker', 'open', 'task', ${WS}, 'someone-else', 100, 0, '{}'::jsonb),
             (${OLD_H}, 'WI-B2', 'dependent', 'open', 'task', ${WS}, NULL, 200, 0, '{}'::jsonb)`;
    await db.sql`
      INSERT INTO harness_shared.work_item_deps
        (workspace_id, blocked_kind, blocked_ref, blocker_kind, blocker_ref, dep_type)
      VALUES ('default', 'issue', 'WI-B2', 'issue', 'WI-B1', 'blocks')`;

    expect(await claim(OLD_H)).toBeNull();

    await reHome('WI-B2', OLD_H, NEW_H);
    await reHome('WI-B1', OLD_H, NEW_H);

    // Refs unchanged — bare on both sides.
    expect(await edges()).toEqual([{ blocked_ref: 'WI-B2', blocker_ref: 'WI-B1' }]);
    expect(await claim(NEW_H)).toBeNull();

    await db.sql`UPDATE harness_shared.work_items SET status='resolved' WHERE feature_id='WI-B1'`;
    expect(await claim(NEW_H)).toBe('WI-B2');
  });
});

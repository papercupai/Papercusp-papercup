/**
 * token-efficiency-prompts-cache-and-behavior-2026-10-11 P-006 — the cache boundary over the REAL su
 * playbook. Clauses: SPEC-P-006, SPEC-P-006-ONCE, SPEC-P-006-STABLE, AUTO-BAR-R-2-P-006 and
 * AUTO-BAR-R-4-P-006.
 *
 * NO FIXTURE DATA. Every prompt input is produced by production code from this checkout:
 *   - the base is `renderSuPlaybook`, the renderer `buildLaunchSpec({ kind: 'su' })` uses, run over
 *     the real prompt sources. That is about 200 KB of markdown with `---` rules, `## ` headings and
 *     `<!-- PAPERCUSP-SU:… -->` HTML comments shaped like the boundary marker;
 *   - the launch-context seam is `composeLaunchContext`, joined exactly as role-launch-spec.ts
 *     joins it (playbook, blank line, boundary, blank line, launch context);
 *   - the mode sections are `composeModePromptSection`, and the precedence trace is
 *     `buildSuInstructionRuntime`;
 *   - the provenance section is generated by `applySuPromptOverlays` itself.
 * Owner ids and launcher ids are parameters, not test data.
 */
import { describe, expect, it } from 'vitest';
import { renderSuPlaybook } from './desktop-install/papercusp-files';
import { composeModePromptSection } from './endpoint-route/routes/agent-mcp/bootstrap-su-shared';
import { PSU_CACHE_BOUNDARY } from './inference-gateway/cache-policy';
import { composeLaunchContext } from './su-launch-context';
import { applySuPromptOverlays, buildSuInstructionRuntime } from './su-persona-render';

const playbook = renderSuPlaybook({ agent: 'claude', profile: 'engineer', tier: 'full' }).then((r) => r.text);

// One runtime per owner: buildSuInstructionRuntime stamps observedAt once, at construction, so
// renders that must be byte-comparable share the same runtime object.
const runtimes = new Map<string, ReturnType<typeof buildSuInstructionRuntime>>();
const runtimeFor = (ownerId: string, mode: 'auto' | 'drain') => {
  const key = `${ownerId}:${mode}`;
  let runtime = runtimes.get(key);
  if (!runtime) {
    runtime = buildSuInstructionRuntime({
      ownerId,
      autoMode: true,
      drainMode: mode === 'drain',
      fleet: null,
      workspaceId: 'papercusp-workspace',
      harnessSlug: 'papercusp',
      planSlug: 'token-efficiency-prompts-cache-and-behavior-2026-10-11',
    });
    runtimes.set(key, runtime);
  }
  return runtime;
};

async function render(opts: { base: string; ownerId: string; mode: 'auto' | 'drain'; launchedBy: string | null }) {
  const modeSection = composeModePromptSection({ autoMode: true, drainMode: opts.mode === 'drain', loopArmed: false });
  const { promptText } = await applySuPromptOverlays({
    basePromptText: opts.base,
    agent: 'claude',
    launchedBy: opts.launchedBy,
    modeSection,
    instructionRuntime: runtimeFor(opts.ownerId, opts.mode),
  });
  return { promptText, modeSection };
}

const count = (text: string, needle: string) => text.split(needle).length - 1;

/** Run `fn` with the reversible-cutover flag set to `value`, restoring the previous value after. */
async function withSplitFlag<T>(value: string, fn: () => Promise<T>): Promise<T> {
  const prev = process.env.PAPERCUSP_CACHE_SPLIT_BOUNDARY;
  process.env.PAPERCUSP_CACHE_SPLIT_BOUNDARY = value;
  try {
    return await fn();
  } finally {
    if (prev === undefined) delete process.env.PAPERCUSP_CACHE_SPLIT_BOUNDARY;
    else process.env.PAPERCUSP_CACHE_SPLIT_BOUNDARY = prev;
  }
}

describe('applySuPromptOverlays over the real su playbook (P-006)', () => {
  it('the base really is the production playbook: large, boundary-free, many sections and rules', async () => {
    const base = await playbook;
    expect(base.startsWith('# Papercusp engineer-collaborator playbook')).toBe(true);
    expect(Buffer.byteLength(base, 'utf8')).toBeGreaterThan(100_000);
    expect(base.match(/^## /gm)?.length ?? 0).toBeGreaterThan(20);
    expect(count(base, PSU_CACHE_BOUNDARY)).toBe(0);
  });

  it('SPEC-P-006 / AUTO-BAR-R-2-P-006: exactly one boundary, right after the playbook and before every per-session section', async () => {
    const base = await playbook;
    const { promptText } = await render({ base, ownerId: 'su-owner-a', mode: 'auto', launchedBy: 'su-launcher-a' });
    expect(count(promptText, PSU_CACHE_BOUNDARY)).toBe(1);
    const boundaryAt = promptText.indexOf(PSU_CACHE_BOUNDARY);
    expect(promptText.slice(0, boundaryAt)).toBe(`${base.replace(/\n+$/, '')}\n\n`);
    for (const heading of [
      '## Provenance — who launched this session',
      '## AUTO mode',
      '## Effective instruction precedence',
    ]) {
      const at = promptText.indexOf(heading, boundaryAt);
      expect(at, heading).toBeGreaterThan(boundaryAt);
      expect(promptText.slice(0, boundaryAt)).not.toContain(`\n${heading}\n`);
    }
  });

  it('AUTO-BAR-R-4-P-006: every per-session section is present byte-for-byte — removing the boundary line yields the boundary-off render', async () => {
    const base = await playbook;
    const opts = { base, ownerId: 'su-owner-a', mode: 'auto' as const, launchedBy: 'su-launcher-a' };
    const on = await withSplitFlag('1', () => render(opts));
    const off = await withSplitFlag('0', () => render(opts));
    expect(count(off.promptText, PSU_CACHE_BOUNDARY)).toBe(0);
    expect(on.promptText.replace(`${PSU_CACHE_BOUNDARY}\n\n`, '')).toBe(off.promptText);
    const tail = on.promptText.slice(on.promptText.indexOf(PSU_CACHE_BOUNDARY));
    expect(tail).toContain(on.modeSection.replace(/\n+$/, ''));
    expect(tail).toContain('You were launched by **su-launcher-a**');
  });

  it('SPEC-P-006-ONCE: a real launch prompt whose launch-context seam already carries the boundary keeps exactly one', async () => {
    const base = await playbook;
    const launchCtx = composeLaunchContext({
      harnessSlug: 'papercusp',
      planSlug: 'token-efficiency-prompts-cache-and-behavior-2026-10-11',
      planTitle: null,
      planNow: null,
      profile: 'engineer',
      fleetRole: null,
    } as Parameters<typeof composeLaunchContext>[0]);
    expect(launchCtx.length).toBeGreaterThan(0);
    // joined exactly as role-launch-spec.ts joins the stable playbook and the launch context
    const seamed = `${base.replace(/\n+$/, '')}\n\n${PSU_CACHE_BOUNDARY}\n\n${launchCtx}`;
    const { promptText } = await render({ base: seamed, ownerId: 'su-owner-a', mode: 'auto', launchedBy: 'su-launcher-a' });
    expect(count(promptText, PSU_CACHE_BOUNDARY)).toBe(1);
    const boundaryAt = promptText.indexOf(PSU_CACHE_BOUNDARY);
    expect(promptText.slice(0, boundaryAt)).toBe(`${base.replace(/\n+$/, '')}\n\n`);
    expect(promptText.indexOf(launchCtx.replace(/\n+$/, ''))).toBeGreaterThan(boundaryAt);
  });

  it('SPEC-P-006-STABLE / AUTO-BAR-R-2-P-006: two owners in different modes share byte-identical text before the boundary', async () => {
    const base = await playbook;
    const a = await render({ base, ownerId: 'su-owner-a', mode: 'auto', launchedBy: 'su-launcher-a' });
    const b = await render({ base, ownerId: 'su-owner-b', mode: 'drain', launchedBy: null });
    const stable = (t: string) => t.slice(0, t.indexOf(PSU_CACHE_BOUNDARY));
    expect(stable(a.promptText).length).toBeGreaterThan(100_000);
    expect(stable(a.promptText)).toBe(stable(b.promptText));
    expect(a.promptText).not.toBe(b.promptText);
    expect(a.promptText).toContain('## AUTO mode');
    expect(b.promptText).toContain('## DRAIN mode');
  });
});

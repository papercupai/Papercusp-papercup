/**
 * EI-19362441037986499 — REAL-PG guard for `attachCompletionEvidenceToSettledItem`.
 *
 * WHY REAL PG, and not another mocked test. The decision this writer acts on is pure and is
 * unit-covered next door (work-item-settled-completion-evidence.test.ts); the tool wiring is
 * unit-covered in agent-tools/work_items/complete.test.ts, where work-items.ts is mocked
 * wholesale. Neither can see the only question that remains: WHAT POSTGRES KEPT. The writer
 * is a hand-written UPDATE against `harness_shared.work_items` with a jsonb `||` payload
 * merge and a workspace-scoped WHERE — a wrong column, a WHERE that matches nothing, or a
 * merge that replaces the wrong key all pass every mocked assertion and lose the evidence
 * exactly as the original defect did. Same reasoning as the sibling migration guards in
 * work-items-terminal-attribution-preserve.integration.test.ts.
 *
 * WHAT IT PINS
 *   1. the UPGRADE — a thin stored record is replaced and ARCHIVED, not deleted;
 *   2. THE POSITIVE CONTROL, and the assertion that distinguishes "preserve" from
 *      "clobber": on a TIE the stored record SURVIVES untouched and the incoming one is
 *      filed beside it. Without this, a writer that always overwrites would pass every
 *      other assertion here;
 *   3. THE STATE IS NEVER WRITTEN — the property the whole separate-writer design exists
 *      for. A terminal→same-terminal re-assert would re-fire `work-item:done:<id>`;
 *   4. the no-op arms — a non-terminal row and an evidence-free call must write NOTHING,
 *      because either one would otherwise reassign completion CREDIT for free.
 */

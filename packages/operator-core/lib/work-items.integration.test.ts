// it and destroyed the stored record instead.
//
// Proven live on WI-6112 (harness_shared.tool_invocations, ORDER BY invoked_at ASC):
//   15:30:03.446  su-055aef7f  state='resolved'  completion=OBJECT  <- rich, FIRST

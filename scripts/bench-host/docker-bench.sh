#!/usr/bin/env bash
# docker-bench — a second, ISOLATED Docker daemon whose whole state lives on the benchmark volume.
#
# Why (plan benchmark-coverage-frontierswe-v2-2026-10-10, P-007, D-012/D-013): benchmark images and task
# scratch are hundreds of GB, and the box's main Docker daemon keeps its data-root on the nearly-full root
# disk and serves the whole fleet. Docker's data-root is daemon-wide, so the only way to put benchmark
# containers on /mnt/bench without moving everyone else is a separate daemon. The benchmark harness spawns
# the `docker` CLI with the inherited environment, so a run opts in with
#     DOCKER_HOST=unix:///run/docker-bench.sock
# and everything it pulls, builds and runs lands under the bench data-root.
#
# Isolation from the main daemon (each item is pinned by scripts/bench-host/docker-bench.test.ts):
#   * own data-root, exec-root, pidfile and socket;
#   * own containerd namespace on the shared system containerd (two daemons in one namespace see each
#     other's tasks);
#   * classic overlay2 store with the containerd snapshotter OFF — with it on, image layers would land in
#     /var/lib/containerd on the root disk, defeating the point;
#   * iptables=false: a second daemon managing the same DOCKER-* chains can disturb the fleet's
#     networking. This script adds the only rules the bench needs (one MASQUERADE rule, one ufw route rule);
#   * its own pre-created bridge and address pools that do not overlap any existing route.
#
# Usage:
#   docker-bench.sh render <dir>   write daemon.json, docker-bench.service and docker-bench-net into <dir>
#                                  (no root needed; what `install` would install)
#   docker-bench.sh install        render into /etc and /usr/local/sbin, add the ufw route rule, enable + start
#   docker-bench.sh uninstall      stop + disable the unit and remove its files (the data-root is KEPT)
#   docker-bench.sh status         unit state + `docker info` against the bench socket
#   docker-bench.sh fixtures       copy alpine + nginx:alpine from the local main daemon, with exact image-ID checks
#
# Overrides (env): BENCH_DATA_ROOT, BENCH_SOCKET, BENCH_EXEC_ROOT, BENCH_BRIDGE, BENCH_BRIDGE_CIDR,
#                  BENCH_POOL_BASE, BENCH_MOUNT, BENCH_CONTAINERD_NS
set -euo pipefail

BENCH_MOUNT="${BENCH_MOUNT:-/mnt/bench}"
BENCH_DATA_ROOT="${BENCH_DATA_ROOT:-$BENCH_MOUNT/docker}"
BENCH_SOCKET="${BENCH_SOCKET:-/run/docker-bench.sock}"
BENCH_EXEC_ROOT="${BENCH_EXEC_ROOT:-/run/docker-bench}"
BENCH_BRIDGE="${BENCH_BRIDGE:-docker-bench0}"
BENCH_BRIDGE_CIDR="${BENCH_BRIDGE_CIDR:-10.231.0.1/24}"
BENCH_POOL_BASE="${BENCH_POOL_BASE:-10.232.0.0/16}"
BENCH_CONTAINERD_NS="${BENCH_CONTAINERD_NS:-bench}"

UNIT=docker-bench.service
ETC_DIR=/etc/docker-bench
NET_HELPER=/usr/local/sbin/docker-bench-net

die() { echo "docker-bench: $*" >&2; exit 2; }

# Network address of the bridge CIDR (10.231.0.1/24 -> 10.231.0.0/24), for the MASQUERADE source match.
bridge_subnet() {
  local ip="${BENCH_BRIDGE_CIDR%/*}" len="${BENCH_BRIDGE_CIDR#*/}"
  IFS=. read -r a b c d <<<"$ip"
  local n=$(( (a<<24 | b<<16 | c<<8 | d) & (0xFFFFFFFF << (32-len)) & 0xFFFFFFFF ))
  echo "$(( n>>24 & 255 )).$(( n>>16 & 255 )).$(( n>>8 & 255 )).$(( n & 255 ))/$len"
}

render_daemon_json() {
  cat <<JSON
{
  "data-root": "$BENCH_DATA_ROOT",
  "exec-root": "$BENCH_EXEC_ROOT",
  "pidfile": "$BENCH_EXEC_ROOT.pid",
  "hosts": ["unix://$BENCH_SOCKET"],
  "containerd": "/run/containerd/containerd.sock",
  "containerd-namespace": "$BENCH_CONTAINERD_NS",
  "containerd-plugins-namespace": "$BENCH_CONTAINERD_NS-plugins",
  "storage-driver": "overlay2",
  "features": { "containerd-snapshotter": false },
  "bridge": "$BENCH_BRIDGE",
  "iptables": false,
  "ip6tables": false,
  "ip-masq": false,
  "ipv6": false,
  "default-address-pools": [{ "base": "$BENCH_POOL_BASE", "size": 24 }],
  "log-driver": "json-file",
  "log-opts": { "max-size": "50m", "max-file": "3" }
}
JSON
}

render_unit() {
  cat <<UNITEOF
[Unit]
Description=Docker daemon for benchmark runs (state on $BENCH_MOUNT; use DOCKER_HOST=unix://$BENCH_SOCKET)
Documentation=file://$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/docker-bench.sh
After=network-online.target containerd.service
Wants=network-online.target
Requires=containerd.service
RequiresMountsFor=$BENCH_MOUNT

[Service]
Type=notify
ExecStartPre=$NET_HELPER up
ExecStart=/usr/bin/dockerd --config-file $ETC_DIR/daemon.json
ExecStopPost=$NET_HELPER down
ExecReload=/bin/kill -s HUP \$MAINPID
TimeoutStartSec=120
Restart=on-failure
RestartSec=5
LimitNOFILE=infinity
LimitNPROC=infinity
TasksMax=infinity
Delegate=yes
KillMode=process
OOMScoreAdjust=-500

[Install]
WantedBy=multi-user.target
UNITEOF
}

render_net_helper() {
  local subnet; subnet="$(bridge_subnet)"
  cat <<NETEOF
#!/usr/bin/env bash
# Generated by scripts/bench-host/docker-bench.sh — bridge + NAT for the docker-bench daemon (iptables=false).
set -euo pipefail
BR=$BENCH_BRIDGE
CIDR=$BENCH_BRIDGE_CIDR
SUBNET=$subnet
case "\${1:-}" in
  up)
    ip link show "\$BR" >/dev/null 2>&1 || ip link add name "\$BR" type bridge
    ip addr replace "\$CIDR" dev "\$BR"
    ip link set "\$BR" up
    iptables -t nat -C POSTROUTING -s "\$SUBNET" ! -o "\$BR" -j MASQUERADE 2>/dev/null \\
      || iptables -t nat -A POSTROUTING -s "\$SUBNET" ! -o "\$BR" -j MASQUERADE
    ;;
  down)
    while iptables -t nat -C POSTROUTING -s "\$SUBNET" ! -o "\$BR" -j MASQUERADE 2>/dev/null; do
      iptables -t nat -D POSTROUTING -s "\$SUBNET" ! -o "\$BR" -j MASQUERADE
    done
    ip link show "\$BR" >/dev/null 2>&1 && ip link del "\$BR" || true
    ;;
  *) echo "usage: \$0 up|down" >&2; exit 2 ;;
esac
NETEOF
}

render() {
  local out="$1"
  mkdir -p "$out"
  render_daemon_json >"$out/daemon.json"
  render_unit >"$out/$UNIT"
  render_net_helper >"$out/docker-bench-net"
  chmod 0755 "$out/docker-bench-net"
}

need_root() { [ "$(id -u)" -eq 0 ] || die "$1 needs root (run with sudo)"; }

install_bench() {
  need_root install
  mountpoint -q "$BENCH_MOUNT" || die "$BENCH_MOUNT is not a mounted filesystem — mount the bench volume first"
  # Refuse to collide with anything already on the bridge address.
  if ip -4 route show | grep -qE "^$(bridge_subnet) " && ! ip link show "$BENCH_BRIDGE" >/dev/null 2>&1; then
    die "$(bridge_subnet) is already routed via another interface; set BENCH_BRIDGE_CIDR"
  fi
  local tmp; tmp="$(mktemp -d)"; trap 'rm -rf "${tmp:-}"' RETURN
  render "$tmp"
  dockerd --validate --config-file "$tmp/daemon.json" >/dev/null
  install -d -m 0755 "$ETC_DIR" "$BENCH_DATA_ROOT"
  install -m 0644 "$tmp/daemon.json" "$ETC_DIR/daemon.json"
  install -m 0755 "$tmp/docker-bench-net" "$NET_HELPER"
  install -m 0644 "$tmp/$UNIT" "/etc/systemd/system/$UNIT"
  if command -v ufw >/dev/null 2>&1 && ufw status | grep -q '^Status: active'; then
    # ufw's default routed policy here is deny; this admits bench-container-initiated traffic (return traffic
    # is already accepted by ufw-before-forward's RELATED,ESTABLISHED rule). ufw skips an existing rule.
    ufw route allow in on "$BENCH_BRIDGE" comment 'docker-bench egress' >/dev/null
  fi
  systemctl daemon-reload
  systemctl enable --now "$UNIT"
  status_bench
}

uninstall_bench() {
  need_root uninstall
  systemctl disable --now "$UNIT" 2>/dev/null || true
  if command -v ufw >/dev/null 2>&1; then ufw route delete allow in on "$BENCH_BRIDGE" >/dev/null 2>&1 || true; fi
  rm -f "/etc/systemd/system/$UNIT" "$NET_HELPER"
  rm -rf "$ETC_DIR"
  systemctl daemon-reload
  echo "docker-bench removed; data-root $BENCH_DATA_ROOT kept"
}

status_bench() {
  systemctl --no-pager --lines=0 status "$UNIT" || true
  DOCKER_HOST="unix://$BENCH_SOCKET" docker info --format \
    'root={{.DockerRootDir}} driver={{.Driver}} containers={{.Containers}} images={{.Images}} server={{.ServerVersion}}'
}

prepare_fixtures() {
  # The daemon is deliberately empty after installation. Native acceptance uses
  # these two local fixtures, not a registry pull or benchmark task image build.
  local source_host="${BENCH_FIXTURE_SOURCE_HOST:-unix:///var/run/docker.sock}"
  local target_host="unix://$BENCH_SOCKET"
  local source_id target_id image current expected i
  local images=(alpine nginx:alpine) ids=()
  source_id="$(docker --host "$source_host" info --format '{{.ID}}')"
  target_id="$(docker --host "$target_host" info --format '{{.ID}}')"
  [ -n "$source_id" ] && [ -n "$target_id" ] && [ "$source_id" != "$target_id" ] \
    || die 'fixture source and benchmark target must be distinct live daemons'
  # Preflight the whole set before writing. Never replace a peer's existing tag.
  for image in "${images[@]}"; do
    expected="$(docker --host "$source_host" image inspect --format '{{.Id}}' "$image")"
    [[ "$expected" =~ ^sha256:[a-f0-9]{64}$ ]] || die "invalid source image ID: $image"
    ids+=("$expected")
    if current="$(docker --host "$target_host" image inspect --format '{{.Id}}' "$image" 2>/dev/null)"; then
      [ "$current" = "$expected" ] || die "fixture tag already names a different image on benchmark daemon: $image"
    fi
  done
  for i in "${!images[@]}"; do
    image="${images[$i]}" expected="${ids[$i]}"
    if current="$(docker --host "$target_host" image inspect --format '{{.Id}}' "$image" 2>/dev/null)"; then
      [ "$current" = "$expected" ] || die "fixture tag changed during preparation: $image"
      echo "DOCKER_BENCH_FIXTURE image=$image id=$expected status=present"
      continue
    fi
    docker --host "$source_host" image save "$image" | docker --host "$target_host" image load
    current="$(docker --host "$target_host" image inspect --format '{{.Id}}' "$image")"
    [ "$current" = "$expected" ] || die "loaded fixture ID differs from source preflight: $image"
    echo "DOCKER_BENCH_FIXTURE image=$image id=$expected status=loaded"
  done
}

case "${1:-}" in
  render) [ -n "${2:-}" ] || die "usage: $0 render <dir>"; render "$2" ;;
  install) install_bench ;;
  uninstall) uninstall_bench ;;
  status) status_bench ;;
  fixtures) prepare_fixtures ;;
  *) die "usage: $0 render <dir> | install | uninstall | status | fixtures" ;;
esac
